package com.dell.spt.load.step.weighted;

import com.dell.spt.base.config.ScenarioConfigurationException;
import com.dell.spt.base.env.Extension;
import com.dell.spt.base.item.op.OpType;
import com.dell.spt.base.load.step.client.LoadStepClientBase;
import com.dell.spt.base.logging.LogUtil;
import com.dell.spt.base.metrics.MetricsManager;
import com.dell.spt.base.util.BinarySizeFormat;
import com.github.akurilov.commons.reflection.TypeUtil;
import com.github.akurilov.commons.system.SizeInBytes;
import com.github.akurilov.confuse.Config;
import com.github.akurilov.confuse.exceptions.InvalidValuePathException;
import com.github.akurilov.confuse.exceptions.InvalidValueTypeException;
import com.github.akurilov.confuse.impl.BasicConfig;
import org.apache.logging.log4j.Level;

import java.util.Arrays;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.NoSuchElementException;

import static com.github.akurilov.commons.collection.TreeUtil.reduceForest;
import static com.github.akurilov.confuse.Config.deepToMap;

public class WeightedLoadStepClient extends LoadStepClientBase<WeightedLoadStepClient> {
	public WeightedLoadStepClient(
					final Config config, final List<Extension> extensions, final List<Config> ctxConfigs,
					final MetricsManager metricsManager) {
		super(config, extensions, ctxConfigs, metricsManager);
	}

	@Override
	public String getTypeName() {
		return WeightedLoadStepExtension.TYPE;
	}

	/**
	 * Each sub-load runs on its context over the base. A context is the base with its own values on
	 * top, so the count and the items of each sub-load are its context's, and the base's are unused.
	 */
	@Override
	protected boolean controlsOperations(final int contextIndex) {
		return contextIndex != BASE_CONFIG;
	}

	/**
	 * Whether {@code ctxConfig} holds the step id it copied from a base that generates its id. A
	 * context without the flag, or without a {@code load.step} section (the configuration then
	 * throws for the missing branch), does not.
	 */
	private static boolean copiedGeneratedStepId(final Config ctxConfig) {
		try {
			return Boolean.TRUE.equals(ctxConfig.val("load-step-idAutoGenerated"));
		} catch (final NoSuchElementException e) {
			return false;
		}
	}

	@Override
	protected WeightedLoadStepClient copyInstance(final Config config, final List<Config> ctxConfigs) {
		return new WeightedLoadStepClient(config, extensions, ctxConfigs, metricsMgr);
	}

	@Override
	protected void init() throws IllegalStateException {
		final String autoStepId = "weighted_" + LogUtil.getDateTimeStamp();
		final Config stepConfig = config.configVal("load-step");
		if (stepConfig.boolVal("idAutoGenerated")) {
			stepConfig.val("id", autoStepId);
		}
		// A context that only copied the base's id runs under the step's; one whose append() set an id
		// keeps it, and the last context's id still names the step below. A context built without the
		// flag, as a caller of the public constructor may pass, keeps its id as before, and one without
		// a load.step section, or whose schema has no string load.step.id, takes the step's from the base at
		// the merge below.
		final String stepId = stepConfig.stringVal("id");
		for (final Config ctxConfig : ctxConfigs) {
			if (copiedGeneratedStepId(ctxConfig)) {
				try {
					ctxConfig.val("load-step-id", stepId);
				} catch (final IllegalArgumentException e) {
					// No id of its own to replace (InvalidValuePathException), or a private schema that cannot
					// hold a string id there (NumberFormatException):
					// the merge gives it the step's.
				}
			}
		}
		final int subStepCount = ctxConfigs.size();

		// 2nd pass: initialize the sub steps
		for (int originIndex = 0; originIndex < subStepCount; originIndex++) {
			final Map<String, Object> mergedConfigTree = reduceForest(
							Arrays.asList(deepToMap(config), deepToMap(ctxConfigs.get(originIndex))));
			Config subConfig = null;
			try {
				subConfig = new BasicConfig(config.pathSep(), config.schema(), mergedConfigTree);
			} catch (final InvalidValueTypeException | InvalidValuePathException e) {
				LogUtil.exception(Level.FATAL, e, "Scenario syntax error");
				throw new ScenarioConfigurationException(e, config);
			}
			final OpType opType = OpType.valueOf(subConfig.stringVal("load-op-type").toUpperCase(Locale.ROOT));
			final int concurrencyLimit = config.intVal("storage-driver-limit-concurrency");
			final Config outputConfig = subConfig.configVal("output");
			final Config metricsConfig = outputConfig.configVal("metrics");
			final SizeInBytes itemDataSize;
			final Object itemDataSizeRaw = subConfig.val("item-data-size");
			if (itemDataSizeRaw instanceof String) {
				itemDataSize = BinarySizeFormat.parseSize((String) itemDataSizeRaw);
			} else {
				itemDataSize = new SizeInBytes(TypeUtil.typeConvert(itemDataSizeRaw, long.class));
			}
			final boolean colorFlag = outputConfig.boolVal("color");
			stepConfig.val("id", subConfig.stringVal("load-step-id")); // Overwrite step id with sub config step id
			initMetrics(originIndex, opType, concurrencyLimit, metricsConfig, itemDataSize, colorFlag);
		}
	}
}
