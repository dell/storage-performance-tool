package com.dell.spt.load.step.weighted;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;

import com.dell.spt.base.concurrent.ServiceTaskExecutor;
import com.dell.spt.base.config.ConfigFormat;
import com.dell.spt.base.config.ConfigUtil;
import com.dell.spt.base.config.InitialConfigSchemaProvider;
import com.dell.spt.base.env.Extension;
import com.dell.spt.base.metrics.MetricsManagerImpl;
import com.dell.spt.base.storage.driver.mock.DummyStorageDriverMockExtension;
import com.dell.spt.base.svc.ServiceUtil;
import com.github.akurilov.confuse.Config;
import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.Test;

/**
 * Each sub-load of a weighted step writes its operation traces and timing metrics under its
 * context's id on every engine, so the step collects each engine's files of each context's id,
 * not only those of the last context, whose id names the step.
 */
class WeightedContextOutputStepIdTest {

	private final MetricsManagerImpl metrics = new MetricsManagerImpl(ServiceTaskExecutor.VT_EXECUTOR);

	@AfterEach
	void shutdown() {
		ServiceUtil.shutdown();
	}

	@Test
	void contextsWithTheirOwnIdsWriteUnderThem() throws Exception {
		final WeightedLoadStepClient step = prototype(false).append(withId("wA")).append(withId("wB"));
		step.init();

		assertEquals("wB", step.loadStepId());
		assertEquals("wA", step.contextOutputStepId(0));
		assertEquals("wB", step.contextOutputStepId(1));
	}

	@Test
	void contextsWithoutIdsWriteUnderTheGeneratedStepId() throws Exception {
		final WeightedLoadStepClient step = prototype(true).append(context()).append(context());
		step.init();

		assertEquals(step.loadStepId(), step.contextOutputStepId(0));
		assertEquals(step.loadStepId(), step.contextOutputStepId(1));
	}

	/** A context without an id keeps the configured id it copied, which the step's then is. */
	@Test
	void aContextWithoutAnIdBesideOneWithItsOwnWritesUnderTheStepId() throws Exception {
		final WeightedLoadStepClient step = prototype(false).append(withId("wA")).append(context());
		step.init();

		assertEquals("configured", step.loadStepId());
		assertEquals("wA", step.contextOutputStepId(0));
		assertEquals("configured", step.contextOutputStepId(1));
	}

	/** Only a context without an id falls back to the step's: an index that names no context is a bug. */
	@Test
	void anIndexThatNamesNoContextFails() throws Exception {
		final WeightedLoadStepClient step = prototype(false).append(withId("wA")).append(withId("wB"));
		step.init();

		assertThrows(IndexOutOfBoundsException.class, () -> step.contextOutputStepId(2));
		assertThrows(IndexOutOfBoundsException.class, () -> step.contextOutputStepId(-1));
	}

	private static Map<String, Object> context() {
		return Map.of("load", Map.of("op", Map.of("weight", 1)));
	}

	private static Map<String, Object> withId(final String id) {
		return Map.of("load", Map.of("op", Map.of("weight", 1), "step", Map.of("id", id)));
	}

	/** A weighted step with the shipped defaults: its id generated, or the configured one. */
	private WeightedLoadStepClient prototype(final boolean generatedId) throws Exception {
		final Config core = ConfigUtil.loadConfig(
						resource("/config/defaults.yaml"), ConfigFormat.YAML, InitialConfigSchemaProvider.provider().schema());
		final Config weighted = ConfigUtil.loadConfig(
						resource("/config/defaults-load-generator-weight.yaml"),
						ConfigFormat.YAML,
						new WeightedLoadStepExtension().schemaProvider().schema());
		final Config config = ConfigUtil.merge(core.pathSep(), List.of(weighted, core));
		config.val("load-step-id", "configured");
		config.val("load-step-idAutoGenerated", generatedId);
		config.val("storage-driver-type", "dummy-mock");
		config.val("load-op-type", "noop");
		final List<Extension> extensions = List.of(new WeightedLoadStepExtension(), new DummyStorageDriverMockExtension<>());
		return new WeightedLoadStepClient(config, extensions, null, metrics);
	}

	private static String resource(final String name) throws IOException {
		try (InputStream stream = WeightedContextOutputStepIdTest.class.getResourceAsStream(name)) {
			return new String(Objects.requireNonNull(stream, name).readAllBytes(), StandardCharsets.UTF_8);
		}
	}
}
