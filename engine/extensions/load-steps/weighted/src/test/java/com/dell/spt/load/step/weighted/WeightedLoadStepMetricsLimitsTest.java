package com.dell.spt.load.step.weighted;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.mockito.Mockito.mock;

import com.dell.spt.base.config.ConfigFormat;
import com.dell.spt.base.config.ConfigUtil;
import com.dell.spt.base.config.InitialConfigSchemaProvider;
import com.dell.spt.base.item.op.OpType;
import com.dell.spt.base.load.step.LoadStepBase;
import com.dell.spt.base.metrics.MetricsConstants;
import com.dell.spt.base.metrics.MetricsManager;
import com.dell.spt.base.metrics.context.MetricsContext;
import com.github.akurilov.confuse.Config;
import java.io.IOException;
import java.io.InputStream;
import java.lang.reflect.Field;
import java.nio.charset.StandardCharsets;
import java.util.List;
import java.util.Map;
import java.util.Objects;
import org.junit.jupiter.api.Test;

/**
 * Each metrics row of a weighted step is one sub-load: it keeps its context's count, and carries the
 * base's time limit, which the step stops on whatever a context says.
 */
class WeightedLoadStepMetricsLimitsTest {

	@Test
	void eachRowKeepsItsContextsCountAndTakesTheBasesTime() throws Exception {
		final Config config = defaultConfig();
		config.val("load-step-id", "weighted-limits-" + System.nanoTime());
		config.val("load-step-idAutoGenerated", false);
		config.val("load-step-limit-time", "12s");
		config.val("load-op-limit-count", 0L);
		config.val("storage-driver-type", "dummy-mock");
		final WeightedLoadStepClient client = new WeightedLoadStepClient(config, List.of(), null, mock(MetricsManager.class))
						.append(Map.of("load", Map.of(
										"op", Map.of("type", "create", "limit", Map.of("count", 50L)),
										"step", Map.of("limit", Map.of("time", "3s")))))
						.append(Map.of("load", Map.of("op", Map.of("type", "read", "limit", Map.of("count", 70L)))));

		client.init();

		final List<MetricsContext<?>> rows = metricsContextsOf(client);
		assertEquals(List.of(OpType.CREATE, OpType.READ), rows.stream().map(MetricsContext::opType).toList());
		assertEquals(50L, limit(rows.get(0), MetricsConstants.METADATA_LIMIT_OP_COUNT));
		assertEquals(70L, limit(rows.get(1), MetricsConstants.METADATA_LIMIT_OP_COUNT));
		for (final MetricsContext<?> row : rows) {
			assertEquals(12L, limit(row, MetricsConstants.METADATA_LIMIT_TIME_SEC), row.opType().name());
		}
	}

	private static long limit(final MetricsContext<?> row, final String key) {
		final Object value = row.metadata().get(key);
		assertNotNull(value, key);
		return ((Number) value).longValue();
	}

	@SuppressWarnings("unchecked")
	private static List<MetricsContext<?>> metricsContextsOf(final LoadStepBase step) throws ReflectiveOperationException {
		final Field field = LoadStepBase.class.getDeclaredField("metricsContexts");
		field.setAccessible(true);
		return (List<MetricsContext<?>>) field.get(step);
	}

	/** The shipped defaults of the engine and of this extension, as the engine merges them. */
	private static Config defaultConfig() throws Exception {
		final Config core = ConfigUtil.loadConfig(
						resource("/config/defaults.yaml"), ConfigFormat.YAML, InitialConfigSchemaProvider.provider().schema());
		final Config weighted = ConfigUtil.loadConfig(
						resource("/config/defaults-load-generator-weight.yaml"),
						ConfigFormat.YAML,
						new WeightedLoadStepExtension().schemaProvider().schema());
		return ConfigUtil.merge(core.pathSep(), List.of(weighted, core));
	}

	private static String resource(final String name) throws IOException {
		try (InputStream stream = WeightedLoadStepMetricsLimitsTest.class.getResourceAsStream(name)) {
			return new String(Objects.requireNonNull(stream, name).readAllBytes(), StandardCharsets.UTF_8);
		}
	}
}
