import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.Timeout;
import org.junit.jupiter.api.io.TempDir;

/**
 * Which count and which items of a weighted step must give each of its two Engine Participants a
 * share. Each sub-load runs on its context over the base, so the rules apply to the contexts, and
 * the base's count and items, which no operation uses, are sliced as they always were.
 *
 * <p>The client step, both slices, the item scatter and the transfer between Engine Participants
 * (RMI over the loopback interface) are the real ones; the storage driver is the dummy mock.
 */
@Timeout(180)
class WeightedLoadStepClientCountSlicesTest {

	private static final String RMI_HOSTNAME = "java.rmi.server.hostname";
	// Bounds each engine to 50 operations per second, should a slice ever run without a count.
	private static final double RATE_LIMIT = 100;
	private static final Duration RUN_TIMEOUT = Duration.ofSeconds(60);
	// Longer than any run here may take, so a step's final entries are still kept when it is read.
	private static final long TERMINAL_RETENTION_MILLIS = TimeUnit.MINUTES.toMillis(10);

	private final MetricsManagerImpl entryMgr = new MetricsManagerImpl(ServiceTaskExecutor.VT_EXECUTOR);
	private final MetricsManagerImpl workerMgr = new MetricsManagerImpl(ServiceTaskExecutor.VT_EXECUTOR);
	private String originalRmiHostname;
	private FileManagerServiceImpl fileService;
	private LoadStepManagerServiceImpl stepManager;
	private Config config;
	private LoadStepClientBase<?> client;

	@TempDir
	Path home;

	@BeforeEach
	void startTheWorker() throws Exception {
		entryMgr.setTerminalRetentionMillis(TERMINAL_RETENTION_MILLIS);
		workerMgr.setTerminalRetentionMillis(TERMINAL_RETENTION_MILLIS);
		final int port;
		try (ServerSocket socket = new ServerSocket(0)) {
			socket.setReuseAddress(true);
			port = socket.getLocalPort();
		}
		originalRmiHostname = System.getProperty(RMI_HOSTNAME);
		System.setProperty(RMI_HOSTNAME, "127.0.0.1");
		// The worker's service threads inherit a home directory of their own, as a separate engine has one.
		ThreadContext.put("home_dir", home.resolve("worker").toString());
		fileService = new FileManagerServiceImpl(port);
		fileService.start();
		stepManager = new LoadStepManagerServiceImpl(port, extensions(), workerMgr);
		stepManager.start();
		ThreadContext.put("home_dir", home.toString());

		config = defaultConfig();
		config.val("load-step-id", "weighted-count-slices-" + UUID.randomUUID());
		config.val("load-step-idAutoGenerated", false);
		config.val("load-step-node-addrs", List.of("127.0.0.1:" + port));
		config.val("load-step-limit-time", 0);
		config.val("storage-driver-type", "dummy-mock");
		config.val("storage-targetBucket-provision", false);
		config.val("output-metrics-timing-persist", false);
		config.val("output-metrics-trace-persist", false);
		config.val("item-data-verify", false);
		config.val("item-input-file", null);
		config.val("item-input-path", null);
		// An operation type that leaves no artifact for the step to merge when it closes: both
		// participants of this test share one JVM's log files.
		config.val("load-op-type", "noop");
		config.val("load-op-limit-rate", RATE_LIMIT);
		config.val("load-op-wait-finish", true);
		config.val("load-op-wait-limit", 1);
	}

	@AfterEach
	void closeAll() throws Exception {
		try {
			if (client != null && !client.isClosed()) {
				client.close();
			}
			if (stepManager != null && !stepManager.isClosed()) {
				stepManager.close();
			}
			if (fileService != null && !fileService.isClosed()) {
				fileService.close();
			}
		} finally {
			ServiceUtil.shutdown();
			ThreadContext.remove("home_dir");
			if (originalRmiHostname == null) {
				System.clearProperty(RMI_HOSTNAME);
			} else {
				System.setProperty(RMI_HOSTNAME, originalRmiHostname);
			}
		}
	}

	/** Each sub-load takes its count from its context, so the base's count of 1 limits nothing. */
	@Test
	void aBaseCountTheContextsOverrideIsNotChecked() {
		config.val("load-op-limit-count", 1L);
		client = new WeightedLoadStepClient(config, extensions(), null, entryMgr)
						.append(Map.of("load", Map.of("op", Map.of("limit", Map.of("count", 4L)))));
		assertTimeoutPreemptively(RUN_TIMEOUT, client::run);

		assertEquals(2, entry(entryMgr, false).successCount);
		assertEquals(2, entry(workerMgr, false).successCount);
		assertEquals(4, entry(entryMgr, true).successCount);
	}

	@Test
	void aContextCountBelowTheEngineCountFailsBeforeTheStepStarts() {
		config.val("load-op-limit-count", 4L);
		client = new WeightedLoadStepClient(config, extensions(), null, entryMgr)
						.append(Map.of("load", Map.of("op", Map.of("limit", Map.of("count", 1L)))));
		final RunTerminalException failure = assertTimeoutPreemptively(
						RUN_TIMEOUT, () -> assertThrows(RunTerminalException.class, client::run));
		assertEquals(IntegrityTerminalException.Category.CONFIGURATION, failure.category());
		assertTrue(failure.getMessage().startsWith("the count limit (1) is below the number of engines (2)"), failure.getMessage());
		assertEquals(List.of(), workerMgr.getTerminalSteps(), "the worker's slice never started");
	}

	/** The sub-load reads its context's items file, so the base's one item is not one per engine short. */
	@Test
	void aBaseItemsFileAContextReplacesIsNotCounted() throws Exception {
		config.val("item-input-file", items("one.csv", 1).toString());
		config.val("load-op-type", "update");
		config.val("load-op-recycle-mode", true);
		config.val("load-op-limit-count", 2L);
		client = new WeightedLoadStepClient(config, extensions(), null, entryMgr)
						.append(Map.of("item", Map.of("input", Map.of("file", items("two.csv", 2).toString()))));
		assertTimeoutPreemptively(RUN_TIMEOUT, client::run);

		assertEquals(1, entry(entryMgr, false).successCount);
		assertEquals(1, entry(workerMgr, false).successCount);
		assertEquals(2, entry(entryMgr, true).successCount);
	}

	/** Only the step's own time limit ends it, so a context's leaves an engine without items to hang. */
	@Test
	void aContextsTimeLimitDoesNotLetAnEngineWithoutItemsStart() throws Exception {
		config.val("load-op-limit-count", 0L);
		client = new WeightedLoadStepClient(config, extensions(), null, entryMgr)
						.append(Map.of(
										"item", Map.of("input", Map.of("file", items("one.csv", 1).toString())),
										"load", Map.of(
														"op", Map.of("type", "read", "recycle", Map.of("mode", true), "limit", Map.of("count", 2L)),
														"step", Map.of("limit", Map.of("time", "2s")))));
		final RunTerminalException failure = assertTimeoutPreemptively(
						RUN_TIMEOUT, () -> assertThrows(RunTerminalException.class, client::run));
		assertEquals(IntegrityTerminalException.Category.INPUT, failure.category());
		assertEquals(
						"the items file has 1 item for 2 engines; each engine needs at least one in a step limited by count: "
										+ "add items, or pass fewer --test-hosts",
						failure.getMessage());
		assertEquals(List.of(), workerMgr.getTerminalSteps(), "the worker's slice never started");
	}

	@Test
	void everyContextAndNotTheBaseControlsTheOperations() {
		final var weighted = new WeightedLoadStepClient(config, extensions(), null, entryMgr);
		assertFalse(weighted.controlsOperations(LoadStepClientBase.BASE_CONFIG));
		assertTrue(weighted.controlsOperations(0));
		assertTrue(weighted.controlsOperations(1));
	}

	private Path items(final String name, final int count) throws IOException {
		final StringBuilder lines = new StringBuilder();
		for (int i = 0; i < count; i++) {
			lines.append("/bucket/item-").append(i).append(',').append(i).append(",10,0/0\n");
		}
		return Files.writeString(home.resolve(name), lines);
	}

	private static List<Extension> extensions() {
		return List.of(new WeightedLoadStepExtension(), new DummyStorageDriverMockExtension<>());
	}

	/** The one entry a metrics manager kept for the step: its fleet's or its node's. */
	private static TerminalStepEntry entry(final MetricsManagerImpl mgr, final boolean distributed) {
		final List<TerminalStepEntry> entries = mgr.getTerminalSteps().stream()
						.filter(entry -> entry.distributed == distributed)
						.toList();
		assertEquals(1, entries.size(), mgr.getTerminalSteps().toString());
		return entries.get(0);
	}

	/** The shipped defaults of the engine and of this extension, as the engine merges them. */
	private static Config defaultConfig() throws Exception {
		final Config core = ConfigUtil.loadConfig(
						resource("/config/defaults.yaml"), ConfigFormat.YAML, InitialConfigSchemaProvider.provider().schema());
		final Config weighted = ConfigUtil.loadConfig(
						resource("/config/defaults-load-generator-weight.yaml"),
						ConfigFormat.YAML,
						new WeightedLoadStepExtension().schemaProvider().schema());
		return ConfigUtil.merge(core.pathSep(), List.of(weighted, core));
	}

	private static String resource(final String name) throws IOException {
		try (InputStream stream = WeightedLoadStepClientCountSlicesTest.class.getResourceAsStream(name)) {
			return new String(stream.readAllBytes(), StandardCharsets.UTF_8);
		}
	}
}
