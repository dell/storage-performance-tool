/**
 * When a sub-load of a weighted step finishes, the weights of those still running are scaled again,
 * as a step written with only them would scale them. Two creates at 1/1 with no limit run beside a
 * sub-load of weight 48 that finishes early; scaled at the start the cycle is 2/2/96, and once the
 * third leaves it, 50/50.
 */
@Timeout(120)
class WeightedLoadStepRetiredSubLoadScaleTest {

	private static final long WAIT_SECONDS = 30;
	private static final int[] SURVIVORS_SCALED = {50, 50, 0
	};

	private final ContextRecordingMetrics metrics = new ContextRecordingMetrics();
	private Config config;

	@TempDir
	Path home;

	@BeforeEach
	void setUp() throws Exception {
		ThreadContext.put("home_dir", home.toString());
		config = defaultConfig();
		config.val("load-step-id", "weighted-retired-scale-" + UUID.randomUUID());
		config.val("load-step-idAutoGenerated", false);
		config.val("load-step-limit-time", 0);
		config.val("storage-driver-type", "dummy-mock");
		config.val("storage-targetBucket-provision", false);
		config.val("output-metrics-timing-persist", false);
		config.val("output-metrics-trace-persist", false);
		config.val("item-data-size", "1KB");
		config.val("item-data-verify", false);
		config.val("item-input-file", null);
		config.val("item-input-path", null);
		config.val("item-output-path", "/bucket");
		config.val("load-op-type", "create");
	}

	@AfterEach
	void tearDown() {
		ServiceUtil.shutdown();
		ThreadContext.remove("home_dir");
	}

	@Test
	void aSubLoadAtItsCountLimitLeavesTheOthersScaledByTheirOwnWeights() throws Exception {
		final Config counted = context(48);
		counted.val("load-op-limit-count", 1000L);
		assertSurvivorsScaled(counted);
		assertEquals(List.of(1000L), successCounts(OpType.CREATE).subList(0, 1));
	}

	@Test
	void aSubLoadAtTheEndOfItsInputLeavesTheOthersScaledByTheirOwnWeights() throws Exception {
		final Config finite = context(48);
		finite.val("load-op-type", "read");
		finite.val("item-input-file", items(20).toString());
		assertSurvivorsScaled(finite);
		assertEquals(List.of(20L), successCounts(OpType.READ));
	}

	private void assertSurvivorsScaled(final Config third) throws Exception {
		final List<Extension> extensions = List.of(new WeightedLoadStepExtension(), new DummyStorageDriverMockExtension<>());
		try (WeightedLoadStepLocal step = new WeightedLoadStepLocal(
						config, extensions, List.of(context(1), context(1), third), metrics)) {
			step.start();
			final RetiringWeightsThrottle throttle = step.weightThrottle();
			// The other two run with no limit, so the step goes on until it is closed.
			final long deadline = System.nanoTime() + TimeUnit.SECONDS.toNanos(WAIT_SECONDS);
			while (throttle.cycleWeights()[2] != 0) {
				assertTrue(System.nanoTime() < deadline, "the third sub-load did not finish");
				Thread.sleep(5);
			}
			assertArrayEquals(SURVIVORS_SCALED, throttle.cycleWeights());
		}
	}

	private Config context(final int weight) {
		final Config context = new BasicConfig(config.pathSep(), config.schema(), Config.deepToMap(config));
		context.val("load-op-weight", weight);
		return context;
	}

	private Path items(final int count) throws IOException {
		final StringBuilder lines = new StringBuilder();
		for (int i = 0; i < count; i++) {
			lines.append("/bucket/item-").append(i).append(',').append(i).append(",10,0/0\n");
		}
		return Files.writeString(home.resolve("items.csv"), lines);
	}

	/** The success counts of the local contexts of one operation type, smallest first. */
	private List<Long> successCounts(final OpType opType) {
		return metrics.contexts.stream()
						.filter(context -> context.opType() == opType)
						.map(context -> context.lastSnapshot().successSnapshot().count())
						.sorted()
						.toList();
	}

	/** Keeps each local context, since the manager's terminal entries hold one per step. */
	private static final class ContextRecordingMetrics extends MetricsManagerImpl {
		final List<MetricsContext<?>> contexts = new CopyOnWriteArrayList<>();

		ContextRecordingMetrics() {
			super(ServiceTaskExecutor.VT_EXECUTOR);
		}

		@Override
		public void unregister(final MetricsContext metricsCtx) {
			super.unregister(metricsCtx);
			if (!(metricsCtx instanceof DistributedMetricsContext)) {
				contexts.add(metricsCtx);
			}
		}
	}

	/** The shipped defaults of the engine and of this extension, as the engine merges them. */
	private static Config defaultConfig() throws Exception {
		final Config core = ConfigUtil.loadConfig(
						resource("/config/defaults.yaml"), ConfigFormat.YAML, InitialConfigSchemaProvider.provider().schema());
		final Config weighted = ConfigUtil.loadConfig(
						resource("/config/defaults-load-generator-weight.yaml"),
						ConfigFormat.YAML,
						new WeightedLoadStepExtension().schemaProvider().schema());
		return ConfigUtil.merge(core.pathSep(), List.of(weighted, core));
	}

	private static String resource(final String name) throws IOException {
		try (InputStream stream = WeightedLoadStepRetiredSubLoadScaleTest.class.getResourceAsStream(name)) {
			return new String(stream.readAllBytes(), StandardCharsets.UTF_8);
		}
	}
}
