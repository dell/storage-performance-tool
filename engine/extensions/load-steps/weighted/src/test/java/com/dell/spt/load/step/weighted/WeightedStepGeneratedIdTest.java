/**
 * Weighted steps with no configured id, run on this engine with the dummy mock driver: each gets its
 * own generated {@code weighted_} id and folder instead of the engine's initial {@code none-} id, so
 * a second such step in one run is not refused for reusing it.
 */
@Timeout(180)
class WeightedStepGeneratedIdTest {

	private static final String ENGINE_INITIAL_ID = "none-20261118.120000.000";
	private static final Duration RUN_TIMEOUT = Duration.ofSeconds(60);
	private static final long TERMINAL_RETENTION_MILLIS = TimeUnit.MINUTES.toMillis(10);
	private static final Map<String, Object> CONTEXT = Map.of(
					"load", Map.of("op", Map.of("weight", 1, "limit", Map.of("count", 20L))));

	private final MetricsManagerImpl metrics = new MetricsManagerImpl(ServiceTaskExecutor.VT_EXECUTOR);

	@TempDir
	Path home;

	@BeforeEach
	void setHome() {
		metrics.setTerminalRetentionMillis(TERMINAL_RETENTION_MILLIS);
		ThreadContext.put("home_dir", home.toString());
	}

	@AfterEach
	void clearHome() {
		ServiceUtil.shutdown();
		ThreadContext.remove("home_dir");
	}

	@Test
	void twoFreshWeightedStepsEachGetTheirOwnGeneratedId() throws Exception {
		final WeightedLoadStepClient prototype = prototype();

		assertTimeoutPreemptively(RUN_TIMEOUT, () -> prototype.append(CONTEXT).run());
		assertTimeoutPreemptively(RUN_TIMEOUT, () -> prototype.append(CONTEXT).run());

		assertTwoGeneratedSteps();
	}

	@Test
	void anAppendCopyOfAWeightedStepThatHasRunGetsItsOwnGeneratedId() throws Exception {
		final WeightedLoadStepClient step = prototype().append(CONTEXT);

		assertTimeoutPreemptively(RUN_TIMEOUT, step::run);
		assertTimeoutPreemptively(RUN_TIMEOUT, () -> step.append(CONTEXT).run());

		assertTwoGeneratedSteps();
	}

	private void assertTwoGeneratedSteps() throws IOException {
		final Set<String> stepIds = metrics.getTerminalSteps().stream()
						.map(entry -> entry.stepId)
						.collect(Collectors.toCollection(TreeSet::new));
		assertEquals(2, stepIds.size(), stepIds.toString());
		for (final String stepId : stepIds) {
			assertTrue(stepId.startsWith("weighted_"), stepId);
			assertTrue(Files.isDirectory(home.resolve("log").resolve(stepId)), stepId);
		}
		for (final TerminalStepEntry entry : metrics.getTerminalSteps()) {
			assertEquals(20, entry.successCount, entry.stepId);
		}
		assertTrue(!Files.exists(home.resolve("log").resolve(ENGINE_INITIAL_ID)), "nothing in the engine's initial folder");
	}

	/** {@code WeightedLoad} as a run with no configured id sees it. */
	private WeightedLoadStepClient prototype() throws Exception {
		final Config core = ConfigUtil.loadConfig(
						resource("/config/defaults.yaml"), ConfigFormat.YAML, InitialConfigSchemaProvider.provider().schema());
		final Config weighted = ConfigUtil.loadConfig(
						resource("/config/defaults-load-generator-weight.yaml"),
						ConfigFormat.YAML,
						new WeightedLoadStepExtension().schemaProvider().schema());
		final Config config = ConfigUtil.merge(core.pathSep(), List.of(weighted, core));
		config.val("load-step-id", ENGINE_INITIAL_ID);
		config.val("load-step-idAutoGenerated", true);
		config.val("load-step-limit-time", 0);
		config.val("load-step-node-addrs", List.of());
		config.val("storage-driver-type", "dummy-mock");
		config.val("storage-targetBucket-provision", false);
		config.val("output-metrics-timing-persist", false);
		config.val("output-metrics-trace-persist", false);
		config.val("item-data-verify", false);
		config.val("item-input-file", null);
		config.val("item-input-path", null);
		// No lifecycle artifact to merge at close, which a CREATE in a test's shared log files would leave.
		config.val("load-op-type", "noop");
		config.val("load-op-wait-finish", true);
		config.val("load-op-wait-limit", 1);
		final List<Extension> extensions = List.of(new WeightedLoadStepExtension(), new DummyStorageDriverMockExtension<>());
		return new WeightedLoadStepClient(config, extensions, null, metrics);
	}

	private static String resource(final String name) throws IOException {
		try (InputStream stream = WeightedStepGeneratedIdTest.class.getResourceAsStream(name)) {
			return new String(Objects.requireNonNull(stream, name).readAllBytes(), StandardCharsets.UTF_8);
		}
	}
}
