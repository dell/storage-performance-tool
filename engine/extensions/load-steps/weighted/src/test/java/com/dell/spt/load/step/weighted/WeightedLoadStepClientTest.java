	@Test
	@DisplayName("getTypeName returns WeightedLoad")
	void testGetTypeName() throws Exception {
		Config cfg = newBaseConfig();
		WeightedLoadStepClient client = new WeightedLoadStepClient(cfg, Collections.<Extension> emptyList(), Collections.emptyList(), null);
		assertEquals(WeightedLoadStepExtension.TYPE, client.getTypeName());
	}

	@Test
	@DisplayName("config(Map) returns new Weighted client with updated config")
	void testCopyViaConfig() throws Exception {
		Config cfg = newBaseConfig();
		WeightedLoadStepClient client = new WeightedLoadStepClient(cfg, Collections.<Extension> emptyList(), null, null);

		// Perform copy via public API to exercise copyInstance
		WeightedLoadStepClient copy = client.config(Map.of("load-step-id", "weighted-copy"));

		assertNotSame(client, copy);
		assertEquals("weighted-copy", copy.loadStepId());
		// Original remains unchanged
		assertEquals("base-step", client.loadStepId());
		assertEquals(WeightedLoadStepExtension.TYPE, copy.getTypeName());
	}

	@Test
	@DisplayName("append(Map) returns new client and preserves contexts")
	void testAppendReturnsNewClient() throws Exception {
		Config cfg = newBaseConfig();
		WeightedLoadStepClient client = new WeightedLoadStepClient(cfg, Collections.<Extension> emptyList(), null, null);

		WeightedLoadStepClient withCtx = client.append(Map.of("load-op-type", "read"));
		assertNotSame(client, withCtx);
		assertEquals("base-step", client.loadStepId());
		assertEquals("base-step", withCtx.loadStepId());
		assertEquals(WeightedLoadStepExtension.TYPE, withCtx.getTypeName());
	}

	private static final String ENGINE_INITIAL_ID = "none-20261118.120000.000";

	/** A weighted step that shows what init() leaves in its configurations and metrics contexts. */
	private static final class InitProbe extends WeightedLoadStepClient {
		InitProbe(final Config config, final List<Config> ctxConfigs) {
			super(config, List.of(), ctxConfigs, null);
		}

		@Override
		protected WeightedLoadStepClient copyInstance(final Config config, final List<Config> ctxConfigs) {
			return new InitProbe(config, ctxConfigs);
		}

		InitProbe withContext(final String stepId) {
			final Map<String, Object> op = Map.of("op", Map.of("limit", Map.of("count", 5)));
			final Map<String, Object> load = new HashMap<>(op);
			if (stepId != null) {
				load.put("step", Map.of("id", stepId));
			}
			return (InitProbe) append(Map.of("load", load));
		}

		/** As a caller of the public constructor may build its contexts: without the id flag. */
		@SuppressWarnings("unchecked")
		InitProbe withoutContextIdFlags() {
			ctxConfigs.replaceAll(ctx -> {
				final Map<String, Object> tree = Config.deepToMap(ctx);
				((Map<String, Object>) ((Map<String, Object>) tree.get("load")).get("step")).remove("idAutoGenerated");
				try {
					return new BasicConfig(ctx.pathSep(), ctx.schema(), tree);
				} catch (final Exception e) {
					throw new AssertionError(e);
				}
			});
			return this;
		}

		/** As a caller of the public constructor may build its contexts: inheriting all of load.step. */
		@SuppressWarnings("unchecked")
		InitProbe withoutContextStepSections() {
			ctxConfigs.replaceAll(ctx -> {
				final Map<String, Object> tree = Config.deepToMap(ctx);
				((Map<String, Object>) tree.get("load")).remove("step");
				try {
					return new BasicConfig(ctx.pathSep(), ctx.schema(), tree);
				} catch (final Exception e) {
					throw new AssertionError(e);
				}
			});
			return this;
		}

		/** As a caller of the public constructor may build its contexts: a schema with no load.step.id. */
		@SuppressWarnings("unchecked")
		InitProbe withoutContextStepIdLeaves() {
			ctxConfigs.replaceAll(ctx -> {
				final Map<String, Object> tree = Config.deepToMap(ctx);
				((Map<String, Object>) ((Map<String, Object>) tree.get("load")).get("step")).remove("id");
				final Map<String, Object> schema = deepCopy(ctx.schema());
				((Map<String, Object>) ((Map<String, Object>) schema.get("load")).get("step")).remove("id");
				try {
					return new BasicConfig(ctx.pathSep(), schema, tree);
				} catch (final Exception e) {
					throw new AssertionError(e);
				}
			});
			return this;
		}

		@SuppressWarnings("unchecked")
		private static Map<String, Object> deepCopy(final Map<String, Object> map) {
			final Map<String, Object> copy = new LinkedHashMap<>();
			map.forEach((key, value) -> copy.put(key, value instanceof Map ? deepCopy((Map<String, Object>) value) : value));
			return copy;
		}

		List<String> contextIds() {
			return ctxConfigs.stream().map(ctx -> ctx.stringVal("load-step-id")).toList();
		}

		List<String> metricsIds() {
			return metricsContexts.stream().map(MetricsContext::loadStepId).toList();
		}
	}

	/** The engine's configuration of a run, as {@code Main} leaves it with or without a configured id. */
	private static InitProbe runConfigStep(final String stepId) throws Exception {
		final Config core = ConfigUtil.loadConfig(
						resource("/config/defaults.yaml"), ConfigFormat.YAML, InitialConfigSchemaProvider.provider().schema());
		final Config weighted = ConfigUtil.loadConfig(
						resource("/config/defaults-load-generator-weight.yaml"),
						ConfigFormat.YAML,
						new WeightedLoadStepExtension().schemaProvider().schema());
		final Config config = ConfigUtil.merge(core.pathSep(), List.of(weighted, core));
		config.val("load-step-id", stepId == null ? ENGINE_INITIAL_ID : stepId);
		config.val("load-step-idAutoGenerated", stepId == null);
		config.val("storage-driver-type", "dummy-mock");
		return new InitProbe(config, null);
	}

	private static String resource(final String name) throws IOException {
		try (InputStream stream = WeightedLoadStepClientTest.class.getResourceAsStream(name)) {
			return new String(Objects.requireNonNull(stream, name).readAllBytes(), StandardCharsets.UTF_8);
		}
	}

	@Test
	@DisplayName("a step with no configured id runs every context under its generated id")
	void aStepWithNoIdRunsEveryContextUnderItsGeneratedId() throws Exception {
		final InitProbe step = runConfigStep(null).withContext(null).withContext(null);

		step.init();

		final String stepId = step.loadStepId();
		assertTrue(stepId.startsWith("weighted_"), stepId);
		assertEquals(List.of(stepId, stepId), step.contextIds());
		assertEquals(List.of(stepId, stepId), step.metricsIds());
	}

	@Test
	@DisplayName("a configured base id names the step and every context")
	void aConfiguredBaseIdIsKept() throws Exception {
		final InitProbe step = runConfigStep("wbase").withContext(null).withContext(null);

		step.init();

		assertEquals("wbase", step.loadStepId());
		assertEquals(List.of("wbase", "wbase"), step.contextIds());
		assertEquals(List.of("wbase", "wbase"), step.metricsIds());
	}

