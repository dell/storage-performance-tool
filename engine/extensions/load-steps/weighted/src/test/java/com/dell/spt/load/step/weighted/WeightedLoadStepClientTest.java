	@Test
	@DisplayName("an id set in the last context stays with it and names the step")
	void anIdInTheLastContextNamesTheStep() throws Exception {
		final InitProbe step = runConfigStep(null).withContext(null).withContext("wctxlast");

		step.init();

		assertEquals("wctxlast", step.loadStepId());
		final String generatedId = step.contextIds().get(0);
		assertTrue(generatedId.startsWith("weighted_"), generatedId);
		assertEquals(List.of(generatedId, "wctxlast"), step.contextIds());
		assertEquals(List.of(generatedId, "wctxlast"), step.metricsIds());
	}

