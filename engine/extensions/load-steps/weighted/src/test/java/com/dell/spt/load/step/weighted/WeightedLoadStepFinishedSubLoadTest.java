package com.dell.spt.load.step.weighted;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTimeoutPreemptively;
import static org.junit.jupiter.api.Assertions.assertTrue;

import com.dell.spt.base.concurrent.ServiceTaskExecutor;
import com.dell.spt.base.config.ConfigFormat;
import com.dell.spt.base.config.ConfigUtil;
import com.dell.spt.base.config.InitialConfigSchemaProvider;
import com.dell.spt.base.env.Extension;
import com.dell.spt.base.item.op.OpType;
import com.dell.spt.base.metrics.MetricsManagerImpl;
import com.dell.spt.base.metrics.context.DistributedMetricsContext;
import com.dell.spt.base.metrics.context.MetricsContext;
import com.dell.spt.base.storage.driver.mock.DummyStorageDriverMockExtension;
import com.dell.spt.base.svc.ServiceUtil;
import com.github.akurilov.confuse.Config;
import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Duration;
import java.util.List;
import java.util.Map;
import java.util.UUID;
import java.util.concurrent.CopyOnWriteArrayList;
import org.apache.logging.log4j.ThreadContext;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.Timeout;
import org.junit.jupiter.api.io.TempDir;

/** When one sub-load of a weighted step finishes, the others carry on to their own limits. */
@Timeout(120)
class WeightedLoadStepFinishedSubLoadTest {

	private static final Duration RUN_TIMEOUT = Duration.ofSeconds(30);

	private final ContextRecordingMetrics metrics = new ContextRecordingMetrics();
	private Config config;

	@TempDir
	Path home;

	@BeforeEach
	void setUp() throws Exception {
		ThreadContext.put("home_dir", home.toString());
		config = defaultConfig();
		config.val("load-step-id", "weighted-finished-sub-load-" + UUID.randomUUID());
		config.val("load-step-idAutoGenerated", false);
		config.val("load-step-limit-time", 0);
		config.val("storage-driver-type", "dummy-mock");
		config.val("storage-targetBucket-provision", false);
		config.val("output-metrics-timing-persist", false);
		config.val("output-metrics-trace-persist", false);
		config.val("item-data-size", "1KB");
		config.val("item-data-verify", false);
		config.val("item-input-file", null);
		config.val("item-input-path", null);
		config.val("item-output-path", "/bucket");
	}

	@AfterEach
	void tearDown() {
		ServiceUtil.shutdown();
		ThreadContext.remove("home_dir");
	}

	@Test
	void unequalCountsBothComplete() {
		run(create(50, 10, 0), create(50, 200, 0));
		assertEquals(List.of(10L, 200L), successCounts(OpType.CREATE));
	}

	@Test
	void unequalWeightsBothComplete() {
		run(create(20, 100, 0), create(80, 100, 0));
		assertEquals(List.of(100L, 100L), successCounts(OpType.CREATE));
	}

	@Test
	void threeContextsAllComplete() {
		run(create(50, 10, 0), create(50, 100, 0), create(50, 100, 0));
		assertEquals(List.of(10L, 100L, 100L), successCounts(OpType.CREATE));
	}

	@Test
	void aRateInOneContextDoesNotStopEither() {
		run(create(50, 60, 200), create(50, 60, 0));
		assertEquals(List.of(60L, 60L), successCounts(OpType.CREATE));
	}

	@Test
	void aContextKeepsItsRateAfterAFiniteInputEnds() throws Exception {
		config.val("load-step-limit-time", "2s");
		run(read(20, items(20)), create(80, 0, 200));
		assertEquals(List.of(20L), successCounts(OpType.READ));
		final long created = successCounts(OpType.CREATE).get(0);
		assertTrue(created >= 200, "created " + created + " in 2 s at 200 op/s");
	}

	@Test
	void withRetryAFiniteInputBesideACountBothComplete() throws Exception {
		config.val("load-op-retry", true);
		run(read(50, items(30)), create(50, 100, 0));
		assertEquals(List.of(30L), successCounts(OpType.READ));
		assertEquals(List.of(100L), successCounts(OpType.CREATE));
	}

	private void run(final Map<String, Object> first, final Map<String, Object> second, final Map<String, Object> third) {
		assertTimeoutPreemptively(RUN_TIMEOUT, () -> new WeightedLoadStepClient(config, extensions(), null, metrics)
						.append(first)
						.append(second)
						.append(third)
						.run());
	}

	private void run(final Map<String, Object> first, final Map<String, Object> second) {
		assertTimeoutPreemptively(RUN_TIMEOUT, () -> new WeightedLoadStepClient(config, extensions(), null, metrics)
						.append(first)
						.append(second)
						.run());
	}

	private static Map<String, Object> create(final int weight, final long count, final double rate) {
		return Map.of("load", Map.of("op", Map.of(
						"type", "create",
						"weight", weight,
						"limit", Map.of("count", count, "rate", rate))));
	}

	private static Map<String, Object> read(final int weight, final Path items) {
		return Map.of(
						"item", Map.of("input", Map.of("file", items.toString())),
						"load", Map.of("op", Map.of("type", "read", "weight", weight)));
	}

	private Path items(final int count) throws IOException {
		final StringBuilder lines = new StringBuilder();
		for (int i = 0; i < count; i++) {
			lines.append("/bucket/item-").append(i).append(',').append(i).append(",10,0/0\n");
		}
		return Files.writeString(home.resolve("items.csv"), lines);
	}

	private List<Long> successCounts(final OpType opType) {
		return metrics.contexts.stream()
						.filter(context -> context.opType() == opType)
						.map(context -> context.lastSnapshot().successSnapshot().count())
						.sorted()
						.toList();
	}

	private static List<Extension> extensions() {
		return List.of(new WeightedLoadStepExtension(), new DummyStorageDriverMockExtension<>());
	}

	/** Keeps each local context, since the manager's terminal entries hold one per step. */
	private static final class ContextRecordingMetrics extends MetricsManagerImpl {
		final List<MetricsContext<?>> contexts = new CopyOnWriteArrayList<>();

		ContextRecordingMetrics() {
			super(ServiceTaskExecutor.VT_EXECUTOR);
		}

		@Override
		public void unregister(final MetricsContext metricsCtx) {
			super.unregister(metricsCtx);
			if (!(metricsCtx instanceof DistributedMetricsContext)) {
				contexts.add(metricsCtx);
			}
		}
	}

	/** The shipped defaults of the engine and of this extension, as the engine merges them. */
	private static Config defaultConfig() throws Exception {
		final Config core = ConfigUtil.loadConfig(
						resource("/config/defaults.yaml"), ConfigFormat.YAML, InitialConfigSchemaProvider.provider().schema());
		final Config weighted = ConfigUtil.loadConfig(
						resource("/config/defaults-load-generator-weight.yaml"),
						ConfigFormat.YAML,
						new WeightedLoadStepExtension().schemaProvider().schema());
		return ConfigUtil.merge(core.pathSep(), List.of(weighted, core));
	}

	private static String resource(final String name) throws IOException {
		try (InputStream stream = WeightedLoadStepFinishedSubLoadTest.class.getResourceAsStream(name)) {
			return new String(stream.readAllBytes(), StandardCharsets.UTF_8);
		}
	}
}
