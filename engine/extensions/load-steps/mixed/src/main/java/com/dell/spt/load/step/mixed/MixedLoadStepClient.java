package com.dell.spt.load.step.mixed;

import static com.dell.spt.base.Exceptions.throwUncheckedIfInterrupted;

import com.dell.spt.base.env.Extension;
import com.dell.spt.base.item.ItemFactory;
import com.dell.spt.base.item.ItemType;
import com.dell.spt.base.item.io.ItemInputFactory;
import com.dell.spt.base.item.op.OpType;
import com.dell.spt.base.load.step.client.ItemInputFileSlicer;
import com.dell.spt.base.load.step.client.LoadStepClientBase;
import com.dell.spt.base.load.step.file.FileManager;
import com.dell.spt.base.logging.LogUtil;
import com.dell.spt.base.logging.Loggers;
import com.dell.spt.base.metrics.MetricsManager;
import com.dell.spt.base.storage.driver.bucket.TargetBucketStep;
import com.dell.spt.base.util.BinarySizeFormat;
import com.github.akurilov.commons.io.Input;
import com.github.akurilov.commons.reflection.TypeUtil;
import com.github.akurilov.commons.system.SizeInBytes;
import com.github.akurilov.confuse.Config;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.stream.Stream;

/**
 * Client-side counterpart of {@link MixedLoadStepLocal}. Responsible for registering one metrics
 * context per enabled operation type (GET, PUT, DELETE) in distributed mode, and for collecting
 * every slice's created items into one file for the cleanup.
 */
@SuppressWarnings({"unchecked", "rawtypes"
})
public final class MixedLoadStepClient extends LoadStepClientBase<MixedLoadStepClient> {

	public MixedLoadStepClient(
					final Config config,
					final List<Extension> extensions,
					final List<Config> ctxConfigs,
					final MetricsManager metricsManager) {
		super(config, extensions, ctxConfigs, metricsManager);
	}

	@Override
	public String getTypeName() {
		return MixedLoadStepExtension.TYPE;
	}

	@Override
	protected boolean mixesOperations() {
		return true;
	}

	/** A mixed step writes new objects only through PUTs; its item input file is its GET/STAT pool. */
	@Override
	protected TargetBucketStep targetBucketStep() {
		return TargetBucketStep.mixed(config.intVal("load-op-weights-put") > 0);
	}

	/**
	 * The one context runs on the base merged with every context in turn. A context is the base with
	 * its own values on top, so the merge takes each value from the last context, or from the base
	 * when there is none.
	 */
	@Override
	protected boolean controlsOperations(final int contextIndex) {
		return contextIndex == (ctxConfigs == null || ctxConfigs.isEmpty() ? BASE_CONFIG : ctxConfigs.size() - 1);
	}

	@Override
	protected MixedLoadStepClient copyInstance(final Config config, final List<Config> ctxConfigs) {
		return new MixedLoadStepClient(config, extensions, ctxConfigs, metricsMgr);
	}

	@Override
	protected void init() throws IllegalStateException {

		final String autoStepId = "mixed_" + LogUtil.getDateTimeStamp();
		final Config stepConfig = config.configVal("load-step");
		if (stepConfig.boolVal("idAutoGenerated")) {
			stepConfig.val("id", autoStepId);
		}

		final int getWeight = config.intVal("load-op-weights-get");
		final int putWeight = config.intVal("load-op-weights-put");
		final int deleteWeight = config.intVal("load-op-weights-delete");
		final int statWeight = config.intVal("load-op-weights-stat");

		// An item output file makes the base client give each remote slice its own file and append
		// them all to this one once the slices close.
		final String itemOutputFile = config.stringVal("item-output-file");
		if (putWeight > 0 && (itemOutputFile == null || itemOutputFile.isEmpty())) {
			config.val(
							"item-output-file",
							MixedLoadStepLocal.defaultPutRemainingFile(stepConfig.stringVal("id")).toString());
		}

		final int concurrencyLimit = config.intVal("storage-driver-limit-concurrency");
		final Config outputConfig = config.configVal("output");
		final Config metricsConfig = outputConfig.configVal("metrics");
		final boolean colorFlag = outputConfig.boolVal("color");

		final SizeInBytes itemDataSize;
		final Object itemDataSizeRaw = config.val("item-data-size");
		if (itemDataSizeRaw instanceof String) {
			itemDataSize = BinarySizeFormat.parseSize((String) itemDataSizeRaw);
		} else {
			itemDataSize = new SizeInBytes(TypeUtil.typeConvert(itemDataSizeRaw, long.class));
		}

		int originIndex = 0;
		if (getWeight > 0) {
			initMetrics(originIndex++, OpType.READ, concurrencyLimit, metricsConfig, itemDataSize, colorFlag);
		}
		if (putWeight > 0) {
			initMetrics(originIndex++, OpType.CREATE, concurrencyLimit, metricsConfig, itemDataSize, colorFlag);
		}
		if (deleteWeight > 0) {
			initMetrics(originIndex++, OpType.DELETE, concurrencyLimit, metricsConfig, itemDataSize, colorFlag);
		}
		if (statWeight > 0) {
			initMetrics(originIndex++, OpType.STAT, concurrencyLimit, metricsConfig, itemDataSize, colorFlag);
		}
	}

	/** Each engine deletes its own share of a DELETE queue file, as it reads its share of the GET/STAT pool's. */
	@Override
	protected List<AutoCloseable> sliceOwnItemFiles(
					final Config config,
					final List<FileManager> fileMgrs,
					final List<Config> configSlices,
					final int batchSize) {
		final String file = MixedLoadStepLocal.resolveDeleteItemsFile(config);
		if (file == null || file.isEmpty()) {
			return List.of();
		}
		final var itemType = ItemType.valueOf(config.stringVal("item-type").toUpperCase(Locale.ROOT));
		return List.of(sliceDeleteItems(
						loadStepId(), file, (ItemFactory) ItemType.getItemFactory(itemType), fileMgrs, configSlices, batchSize));
	}

	/**
	 * An engine gets no rows when the file has fewer rows than there are engines, which is fine: its
	 * queue is just empty, as any queue becomes. A file with no rows at all still ends the run.
	 */
	static ItemInputFileSlicer sliceDeleteItems(
					final String stepId,
					final String file,
					final ItemFactory factory,
					final List<FileManager> fileMgrs,
					final List<Config> configSlices,
					final int batchSize) {
		if (!Files.exists(Path.of(file))) {
			throw MixedLoadStepLocal.itemsFileFailure("delete items file was not found", null);
		}
		try (final Input input = ItemInputFactory.createFileItemInput(factory, file)) {
			if (input == null) {
				throw MixedLoadStepLocal.itemsFileFailure("delete items file could not be opened", null);
			}
			final var slicer = new ItemInputFileSlicer(
							stepId, fileMgrs, configSlices, input, batchSize, MixedLoadStepLocal.DELETE_ITEMS_FILE);
			if (slicer.distributedItems() == 0) {
				slicer.close();
				throw MixedLoadStepLocal.itemsFileFailure("delete items file has no items", null);
			}
			return slicer;
		} catch (final RuntimeException e) {
			throw e;
		} catch (final Exception e) {
			throwUncheckedIfInterrupted(e);
			throw MixedLoadStepLocal.itemsFileFailure("delete items file could not be read", e);
		}
	}

	/** Checks that the collected file lists every item the step created. */
	@Override
	protected void itemOutputCollected(final String itemOutputFile, final Map<OpType, Long> successCounts)
					throws IOException {
		if (config.intVal("load-op-weights-put") <= 0) {
			return;
		}
		final Long created = successCounts.get(OpType.CREATE);
		if (created == null) {
			Loggers.ERR.warn(
							"{}: the final CREATE count is unavailable, so \"{}\" was not checked against it",
							loadStepId(),
							itemOutputFile);
			return;
		}
		final long listed = listedItemCount(Path.of(itemOutputFile));
		if (listed < created) {
			Loggers.ERR.error(
							"{}: \"{}\" lists {} of the {} items the step created; a cleanup that reads it can leave up to {}"
											+ " objects behind",
							loadStepId(),
							itemOutputFile,
							listed,
							created,
							created - listed);
		} else if (listed > created) {
			Loggers.ERR.warn(
							"{}: \"{}\" lists {} items, more than the {} the step created",
							loadStepId(),
							itemOutputFile,
							listed,
							created);
		} else {
			Loggers.MSG.info("{}: \"{}\" lists all {} items the step created", loadStepId(), itemOutputFile, created);
		}
	}

	/** Counts the lines of an item list; one item per line, so any byte is a valid character. */
	static long listedItemCount(final Path itemList) throws IOException {
		if (!Files.exists(itemList)) {
			return 0;
		}
		try (final Stream<String> lines = Files.lines(itemList, StandardCharsets.ISO_8859_1)) {
			return lines.count();
		}
	}
}
