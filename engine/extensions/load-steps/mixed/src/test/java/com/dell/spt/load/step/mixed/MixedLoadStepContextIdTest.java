/**
 * The step id a mixed slice runs under, with its contexts as the entry's {@code append()} makes
 * them. A mixed step merges its contexts into one, so an id in an appended context does not name
 * the step: the slice generates a {@code mixed_} id, as it always has.
 */
class MixedLoadStepContextIdTest {

	private static final String ENGINE_INITIAL_ID = "none-20261118.120000.000";
	// What the entry generated and sends each slice, with the base flag false. Each slice gets its own, so
	// that a slice's close never meets the lifecycle file of another test's slice in a shared log folder.
	private static final AtomicInteger ENTRY_STEP_IDS = new AtomicInteger();

	@TempDir
	Path home;

	@BeforeEach
	void setHome() {
		ThreadContext.put("home_dir", home.toString());
	}

	@AfterEach
	void clearContext() {
		ThreadContext.remove("home_dir");
		ThreadContext.remove("step_id");
	}

	@Test
	void anIdInAMixedContextDoesNotNameTheSlice() throws Exception {
		final String sliceId = sliceStepId(Map.of("load", Map.of("step", Map.of("id", "mctx"))));

		assertTrue(sliceId.startsWith("mixed_"), sliceId);
	}

	@Test
	void aMixedContextWithNoIdGeneratesTheSliceId() throws Exception {
		final String sliceId = sliceStepId(Map.of());

		assertTrue(sliceId.startsWith("mixed_"), sliceId);
	}

	@Test
	void anIdInAMixedContextKeepsTheFlagItCopied() throws Exception {
		final List<Config> contexts = appendedContexts(Map.of("load", Map.of("step", Map.of("id", "mctx"))));

		assertEquals("mctx", contexts.get(0).stringVal("load-step-id"));
		assertTrue(contexts.get(0).boolVal("load-step-idAutoGenerated"), "as copied from the base");
	}

	/** The id a slice's init() resolves, given the contexts that {@code append(context)} makes. */
	private String sliceStepId(final Map<String, Object> context) throws Exception {
		final List<Config> contexts = appendedContexts(context);
		final Config sliceBase = runConfig();
		sliceBase.val("load-step-id", "mixed_20261118.120000." + ENTRY_STEP_IDS.incrementAndGet() + "-" + System.nanoTime());
		sliceBase.val("load-step-idAutoGenerated", false);
		final var slice = new MixedLoadStepLocal(
						sliceBase,
						List.of(new MixedLoadStepExtension(), new DummyStorageDriverMockExtension<>()),
						contexts,
						mock(MetricsManager.class));
		try {
			assertFalse(slice.isStarted());
			slice.init();
			return ThreadContext.get("step_id");
		} finally {
			slice.close();
		}
	}

	/** The contexts of an id-less mixed step after one {@code append(context)}, as sent to a slice. */
	@SuppressWarnings("unchecked")
	private List<Config> appendedContexts(final Map<String, Object> context) throws Exception {
		final Config base = runConfig();
		base.val("load-step-id", ENGINE_INITIAL_ID);
		base.val("load-step-idAutoGenerated", true);
		final MixedLoadStepClient step = new MixedLoadStepClient(base, List.of(), null, null).append(context);
		final Field field = LoadStepBase.class.getDeclaredField("ctxConfigs");
		field.setAccessible(true);
		return ((List<Config>) field.get(step)).stream().map(ctx -> (Config) new BasicConfig(ctx)).toList();
	}

	/** The shipped defaults with a dummy driver and the item files in the test's home. */
	private Config runConfig() throws Exception {
		final Config core = ConfigUtil.loadConfig(
						resource("/config/defaults.yaml"), ConfigFormat.YAML, InitialConfigSchemaProvider.provider().schema());
		final Config mixed = ConfigUtil.loadConfig(
						resource("/config/defaults-load-op-mixed.yaml"),
						ConfigFormat.YAML,
						new MixedLoadStepExtension().schemaProvider().schema());
		final Config config = ConfigUtil.merge(core.pathSep(), List.of(mixed, core));
		config.val("storage-driver-type", "dummy-mock");
		config.val("item-output-file", home.resolve("put-remaining.csv").toString());
		// PUT and DELETE only, over a pool of one item, so init() needs no seed items for GET and STAT.
		config.val("load-op-weights-get", 0);
		config.val("load-op-weights-stat", 0);
		config.val("load-op-weights-put", 50);
		config.val("load-op-weights-delete", 50);
		config.val("item-input-path", "/source");
		config.val("item-input-file", Files.write(
						home.resolve("pool.csv"), List.of(new DataItemImpl("/bench/a", 0, 1024).toString())).toString());
		return config;
	}

	private static String resource(final String name) throws IOException {
		try (InputStream stream = MixedLoadStepContextIdTest.class.getResourceAsStream(name)) {
			return new String(Objects.requireNonNull(stream, name).readAllBytes(), StandardCharsets.UTF_8);
		}
	}
}
