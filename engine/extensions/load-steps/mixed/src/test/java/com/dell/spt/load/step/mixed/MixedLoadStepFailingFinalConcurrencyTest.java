/**
 * A mixed step whose generator stops on a failure thrown out of the driver's put, while the driver
 * holds accepted operations unsent, fails with a terminal failure and still ends with no operation
 * counted active: the stop settles the held operations as unattempted, and the generator counts
 * them out.
 */
@Timeout(120)
class MixedLoadStepFailingFinalConcurrencyTest {

	/** Operations the driver sends before it holds every later one unsent. */
	private static final long SENT = 200;

	/** Operations the driver accepts and holds before the injected failure. */
	private static final long HELD_BEFORE_FAILURE = 6;

	@TempDir
	Path home;

	@BeforeEach
	void setUp() {
		ThreadContext.put("home_dir", home.toString());
	}

	@AfterEach
	void tearDown() {
		ThreadContext.remove("home_dir");
	}

	@Test
	void anErrorFromPutWithOperationsHeldUnsentEndsWithNoneCountedActive() throws Exception {
		failStep(new LinkageError("attempted duplicate class definition"));
	}

	@Test
	void anUnexpectedExceptionFromPutWithOperationsHeldUnsentEndsWithNoneCountedActive() throws Exception {
		failStep(new IllegalStateException("synthetic prepare failure"));
	}

	private void failStep(final Throwable injected) throws Exception {
		final HoldingDriverFactory drivers = new HoldingDriverFactory(injected);
		final String stepId = "mixed-failing-final-active-" + UUID.randomUUID();
		final FinalCountsMetricsManager metrics = new FinalCountsMetricsManager();
		Throwable thrown = null;
		final long startNanos = System.nanoTime();
		try {
			new MixedLoadStepClient(stepConfig(stepId), List.of(new MixedLoadStepExtension(), drivers), null, metrics).run();
		} catch (final Throwable t) {
			thrown = t;
		}
		final long elapsedMillis = TimeUnit.NANOSECONDS.toMillis(System.nanoTime() - startNanos);
		final long unattempted = drivers.created.stream()
						.mapToLong(driver -> driver.operationLifecycle().counters().unattempted())
						.sum();
		final Map<OpType, Long> concurrency = metrics.finalConcurrency(stepId);
		assertTrue(drivers.injectedAt.get() > 0, "the failure was injected");
		assertNotNull(thrown, "the step fails");
		assertNotNull(IntegrityTerminalException.find(thrown), "with a terminal failure: " + thrown);
		assertTrue(elapsedMillis < 15_000, "before its time limit: " + elapsedMillis);
		assertEquals(SENT, drivers.sent.sum(), "operations the driver sent");
		assertEquals(SENT, metrics.counted(stepId), "operations the step counted");
		assertTrue(unattempted > 0, "the driver held operations unsent at the stop");
		assertEquals(4, concurrency.size(), "a final row for each operation type: " + concurrency);
		for (final Map.Entry<OpType, Long> entry : concurrency.entrySet()) {
			assertEquals(0L, entry.getValue(),
							entry.getKey() + " counted active at the end, with " + unattempted + " unattempted: " + concurrency);
		}
	}

	private Config stepConfig(final String stepId) throws Exception {
		final Config config = defaultConfig();
		config.val("load-step-id", stepId);
		config.val("load-step-idAutoGenerated", false);
		config.val("load-step-limit-time", "30s");
		config.val("load-op-limit-count", 0L);
		config.val("load-op-weights-get", 45);
		config.val("load-op-weights-put", 15);
		config.val("load-op-weights-delete", 10);
		config.val("load-op-weights-stat", 30);
		config.val("storage-driver-type", HoldingDriverFactory.TYPE);
		config.val("storage-driver-limit-concurrency", 16);
		config.val("storage-targetBucket-provision", false);
		config.val("item-data-size", "1KB");
		config.val("item-output-path", "/bucket");
		final List<String> seedItems = new ArrayList<>();
		for (int i = 0; i < 200; i++) {
			seedItems.add(new DataItemImpl("/bucket/seed-" + i, 0, 1024).toString());
		}
		config.val("item-input-file", Files.write(home.resolve("seeds.csv"), seedItems).toString());
		return config;
	}

	private static Config defaultConfig() throws Exception {
		final Config core = ConfigUtil.loadConfig(
						resource("/config/defaults.yaml"), ConfigFormat.YAML, InitialConfigSchemaProvider.provider().schema());
		final Config mixed = ConfigUtil.loadConfig(
						resource("/config/defaults-load-op-mixed.yaml"),
						ConfigFormat.YAML,
						new MixedLoadStepExtension().schemaProvider().schema());
		return ConfigUtil.merge(core.pathSep(), List.of(mixed, core));
	}

	private static String resource(final String name) throws IOException {
		try (InputStream stream = MixedLoadStepFailingFinalConcurrencyTest.class.getResourceAsStream(name)) {
			return new String(stream.readAllBytes(), StandardCharsets.UTF_8);
		}
	}

	@SuppressWarnings({"rawtypes", "unchecked"
	})
	static final class HoldingDriverFactory implements StorageDriverFactory {

		static final String TYPE = "mixed-failing-holding-mock";
		private static final long HOLD_PARK_NANOS = TimeUnit.MILLISECONDS.toNanos(1);

		final LongAdder sent = new LongAdder();
		final AtomicLong prepared = new AtomicLong();
		final AtomicLong injectedAt = new AtomicLong();
		final List<StorageDriver<?, ?>> created = new CopyOnWriteArrayList<>();
		private final Throwable injected;

		HoldingDriverFactory(final Throwable injected) {
			this.injected = injected;
		}

		@Override
		public String id() {
			return TYPE;
		}

		@Override
		public SchemaProvider schemaProvider() {
			return null;
		}

		@Override
		public void install(final Path dstPath) {}

		@Override
		public Config defaults(final Path appHomePath) {
			return null;
		}

		@Override
		public StorageDriver create(
						final String stepId, final DataInput dataInput, final Config storageConfig, final boolean verifyFlag,
						final int batchSize) {
			final StorageDriver driver = new CoopStorageDriverMock(stepId, dataInput, storageConfig, verifyFlag, batchSize) {
				@Override
				protected boolean prepare(final Operation op) {
					final long n = prepared.incrementAndGet();
					if (n == SENT + HELD_BEFORE_FAILURE + 1) {
						injectedAt.set(n);
						if (injected instanceof Error error) {
							throw error;
						}
						throw (RuntimeException) injected;
					}
					return super.prepare(op);
				}

				@Override
				protected boolean submit(final Operation op) {
					synchronized (sent) {
						if (sent.sum() >= SENT) {
							LockSupport.parkNanos(HOLD_PARK_NANOS);
							return false;
						}
						sent.increment();
					}
					return super.submit(op);
				}

				@Override
				protected int submit(final List ops, final int from, final int to) {
					var i = from;
					while (i < to && submit((Operation) ops.get(i))) {
						i++;
					}
					return i - from;
				}
			};
			created.add(driver);
			return driver;
		}
	}
}
