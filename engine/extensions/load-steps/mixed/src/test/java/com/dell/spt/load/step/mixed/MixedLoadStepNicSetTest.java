/** With one target bucket, a mixed step's PUTs copy from item.input.path, which a NIC set rejects. */
@SuppressWarnings({"rawtypes", "unchecked"
})
class MixedLoadStepNicSetTest {

	@TempDir
	Path home;

	@Test
	void copyingPutsFailBeforeTheDriver() throws Exception {
		final Config config = defaultConfig();
		config.val("load-step-id", "mixed-nic-set-" + java.util.UUID.randomUUID());
		config.val("load-step-idAutoGenerated", false);
		config.val("storage-driver-type", "s3");
		config.val("storage-net-interfaces", List.of("ens2np0"));
		config.val("load-op-weights-get", 0);
		config.val("load-op-weights-stat", 0);
		config.val("load-op-weights-put", 50);
		config.val("load-op-weights-delete", 50);
		config.val("item-input-path", "/source");
		config.val("item-output-file", home.resolve("put-remaining.csv").toString());
		config.val("item-input-file", Files.write(
						home.resolve("pool.csv"), List.of(new DataItemImpl("/bench/a", 0, 1024).toString())).toString());
		final NicSetDriverFactory factory = mock(NicSetDriverFactory.class);
		when(factory.id()).thenReturn("s3");
		final var step = new MixedLoadStepLocal(config, List.of(factory), List.of(), mock(MetricsManager.class));
		try {
			final var failure = assertThrows(IllegalStateException.class, step::init);
			assertInstanceOf(IllegalConfigurationException.class, failure.getCause());
			assertTrue(failure.getCause().getMessage().contains("storage.net.interfaces"), failure.getCause().getMessage());
			verify(factory, never()).create(anyString(), any(), any(), anyBoolean(), anyInt());
		} finally {
			step.close();
		}
	}

	/** The shipped defaults of the engine and of this extension, as the engine merges them. */
	private static Config defaultConfig() throws Exception {
		final Config core = ConfigUtil.loadConfig(
						resource("/config/defaults.yaml"), ConfigFormat.YAML, InitialConfigSchemaProvider.provider().schema());
		final Config mixed = ConfigUtil.loadConfig(
						resource("/config/defaults-load-op-mixed.yaml"),
						ConfigFormat.YAML,
						new MixedLoadStepExtension().schemaProvider().schema());
		return ConfigUtil.merge(core.pathSep(), List.of(mixed, core));
	}

	private static String resource(final String name) throws IOException {
		try (InputStream stream = MixedLoadStepNicSetTest.class.getResourceAsStream(name)) {
			return new String(stream.readAllBytes(), StandardCharsets.UTF_8);
		}
	}
}
