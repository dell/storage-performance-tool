/**
 * A mixed step whose driver's dispatch task meets an {@link Error} fails with a terminal failure
 * well before its limits, logs the cause once, and ends with no operation counted active. Before,
 * the driver stopped sending without a message and the step ran to its time limit as a success.
 */
@Timeout(120)
class MixedLoadStepDispatchFailureTest {

	/** The submit that throws; the ones before it are sent. */
	private static final long FAIL_AT = 200;

	private static final String TIME_LIMIT = "30s";
	private static final long WELL_BEFORE_LIMIT_MILLIS = 15_000;

	@TempDir
	Path home;

	@BeforeEach
	void setUp() {
		ThreadContext.put("home_dir", home.toString());
	}

	@AfterEach
	void tearDown() {
		ThreadContext.remove("home_dir");
	}

	@Test
	void aTimeLimitedStepFailsOnADispatchError() throws Exception {
		failStep(0L);
	}

	@Test
	void aCountLimitedStepFailsOnADispatchError() throws Exception {
		failStep(2_000L);
	}

	private void failStep(final long countLimit) throws Exception {
		final LinkageError injected = new LinkageError("attempted duplicate class definition");
		final FailingDriverFactory drivers = new FailingDriverFactory(injected);
		final String stepId = "mixed-dispatch-failure-" + UUID.randomUUID();
		final FinalCountsMetricsManager metrics = new FinalCountsMetricsManager();
		Throwable thrown = null;
		final long startNanos = System.nanoTime();
		try (ErrorLogCapture log = new ErrorLogCapture()) {
			try {
				final Config config = stepConfig(stepId);
				config.val("load-op-limit-count", countLimit);
				new MixedLoadStepClient(config, List.of(new MixedLoadStepExtension(), drivers), null, metrics).run();
			} catch (final Throwable t) {
				thrown = t;
			}
			final long elapsedMillis = TimeUnit.NANOSECONDS.toMillis(System.nanoTime() - startNanos);
			assertTrue(drivers.failedAt.get() > 0, "the failure was injected");
			assertNotNull(thrown, "the step fails");
			final IntegrityTerminalException terminal = IntegrityTerminalException.find(thrown);
			assertNotNull(terminal, "with a terminal failure: " + thrown);
			assertSame(injected, rootCause(terminal), "caused by the dispatch error: " + thrown);
			assertTrue(elapsedMillis < WELL_BEFORE_LIMIT_MILLIS, "well before its time limit: " + elapsedMillis);
			final List<String> errors = log.errorsContaining("");
			assertEquals(1, errors.size(), "one ERROR line: " + errors);
			assertTrue(errors.get(0).contains(injected.toString()), errors.get(0));
		}
		final Map<OpType, Long> concurrency = metrics.finalConcurrency(stepId);
		assertEquals(4, concurrency.size(), "a final row for each operation type: " + concurrency);
		for (final Map.Entry<OpType, Long> entry : concurrency.entrySet()) {
			assertEquals(0L, entry.getValue(), entry.getKey() + " counted active at the end: " + concurrency);
		}
	}

	private static Throwable rootCause(final Throwable outer) {
		var current = outer;
		while (current.getCause() != null && current.getCause() != current) {
			current = current.getCause();
		}
		return current;
	}

	private Config stepConfig(final String stepId) throws Exception {
		final Config config = defaultConfig();
		config.val("load-step-id", stepId);
		config.val("load-step-idAutoGenerated", false);
		config.val("load-step-limit-time", TIME_LIMIT);
		config.val("load-op-weights-get", 45);
		config.val("load-op-weights-put", 15);
		config.val("load-op-weights-delete", 10);
		config.val("load-op-weights-stat", 30);
		config.val("storage-driver-type", FailingDriverFactory.TYPE);
		config.val("storage-driver-limit-concurrency", 16);
		config.val("storage-targetBucket-provision", false);
		config.val("item-data-size", "1KB");
		config.val("item-output-path", "/bucket");
		final List<String> seedItems = new ArrayList<>();
		for (int i = 0; i < 200; i++) {
			seedItems.add(new DataItemImpl("/bucket/seed-" + i, 0, 1024).toString());
		}
		config.val("item-input-file", Files.write(home.resolve("seeds.csv"), seedItems).toString());
		return config;
	}

	private static Config defaultConfig() throws Exception {
		final Config core = ConfigUtil.loadConfig(
						resource("/config/defaults.yaml"), ConfigFormat.YAML, InitialConfigSchemaProvider.provider().schema());
		final Config mixed = ConfigUtil.loadConfig(
						resource("/config/defaults-load-op-mixed.yaml"),
						ConfigFormat.YAML,
						new MixedLoadStepExtension().schemaProvider().schema());
		return ConfigUtil.merge(core.pathSep(), List.of(mixed, core));
	}

	private static String resource(final String name) throws IOException {
		try (InputStream stream = MixedLoadStepDispatchFailureTest.class.getResourceAsStream(name)) {
			return new String(stream.readAllBytes(), StandardCharsets.UTF_8);
		}
	}

	@SuppressWarnings({"rawtypes", "unchecked"
	})
	static final class FailingDriverFactory implements StorageDriverFactory {

		static final String TYPE = "mixed-dispatch-failing-mock";

		final AtomicLong submits = new AtomicLong();
		final AtomicLong failedAt = new AtomicLong();
		private final Error injected;

		FailingDriverFactory(final Error injected) {
			this.injected = injected;
		}

		@Override
		public String id() {
			return TYPE;
		}

		@Override
		public SchemaProvider schemaProvider() {
			return null;
		}

		@Override
		public void install(final Path dstPath) {}

		@Override
		public Config defaults(final Path appHomePath) {
			return null;
		}

		@Override
		public StorageDriver create(
						final String stepId, final DataInput dataInput, final Config storageConfig, final boolean verifyFlag,
						final int batchSize) {
			return new CoopStorageDriverMock(stepId, dataInput, storageConfig, verifyFlag, batchSize) {
				@Override
				protected boolean submit(final Operation op) {
					final long n = submits.incrementAndGet();
					if (n == FAIL_AT) {
						failedAt.set(n);
						throw injected;
					}
					return super.submit(op);
				}
			};
		}
	}
}
