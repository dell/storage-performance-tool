/**
 * A split READ in a timed mixed step, on a driver that ends the read at its last range ({@code
 * finishCompositeRead}) as s3 and s3-aws do: the read retires once, whether its last range is
 * answered while the step runs or after the stop has closed admission.
 */
@Timeout(120)
class MixedLoadStepSplitReadFinishTest {

	private static final long SMALL = 64;
	private static final long LARGE = 1024;

	@TempDir
	Path home;

	@BeforeEach
	void setUp() {
		ThreadContext.put("home_dir", home.toString());
	}

	@AfterEach
	void tearDown() {
		ThreadContext.remove("home_dir");
	}

	/** Both ranges answered while the step runs; the read ends on the thread of its last range. */
	@Test
	void aReadEndedAtItsLastRangeRetiresOnce() throws Exception {
		final Drivers drivers = new Drivers(true, false);
		final Map<OpType, Long> concurrency = run(drivers);

		assertEquals(1, drivers.kickoffs.get(), "kickoffs");
		assertEquals(2, drivers.rangeResults.get(), "range results");
		assertEquals(1, drivers.directFinishes.get(), "reads ended at their last range");
		assertEquals(0, drivers.queuedFinalizations.get(), "queued finalizations");
		final OperationLifecycleCounters counters = drivers.counters();
		assertEquals(1, counters.unresolved(), "only the plain READ is unresolved: " + counters);
		assertEquals(1L, concurrency.get(OpType.READ), "only the plain READ stays active: " + concurrency);
	}

	/** The last range is answered only after the stop closed admission; the read still ends, once. */
	@Test
	void aReadWhoseLastRangeEndsAfterTheStopRetiresOnce() throws Exception {
		final Drivers drivers = new Drivers(true, true);
		final Map<OpType, Long> concurrency = run(drivers);

		assertEquals(1, drivers.kickoffs.get(), "kickoffs");
		assertEquals(2, drivers.rangeResults.get(), "range results");
		assertEquals(true, drivers.lastRangeAfterStop.get(), "the last range ended after admission closed");
		assertEquals(1, drivers.directFinishes.get(), "reads ended at their last range");
		assertEquals(0, drivers.queuedFinalizations.get(), "queued finalizations");
		final OperationLifecycleCounters counters = drivers.counters();
		assertEquals(1, counters.unresolved(), "only the plain READ is unresolved: " + counters);
		assertEquals(1L, concurrency.get(OpType.READ), "only the plain READ stays active: " + concurrency);
	}

	private Map<OpType, Long> run(final Drivers drivers) throws Exception {
		final String stepId = "mixed-split-finish-" + UUID.randomUUID();
		final FinalCountsMetricsManager metrics = new FinalCountsMetricsManager();
		new MixedLoadStepClient(stepConfig(stepId), List.of(new MixedLoadStepExtension(), drivers), null, metrics).run();
		assertEquals(2, drivers.admitted.get(), "READs the driver admitted");
		return metrics.finalConcurrency(stepId);
	}

	private Config stepConfig(final String stepId) throws Exception {
		final Config config = MixedLoadStepCompositeStopTest.defaultConfig();
		config.val("load-step-id", stepId);
		config.val("load-step-idAutoGenerated", false);
		config.val("load-step-limit-time", "2s");
		config.val("load-op-limit-count", 0L);
		config.val("load-op-wait-limit", 1);
		config.val("load-batch-size", 1);
		config.val("load-op-weights-get", 10_000);
		config.val("load-op-weights-put", 0);
		config.val("load-op-weights-delete", 0);
		config.val("load-op-weights-stat", 1);
		config.val("storage-driver-type", Drivers.TYPE);
		config.val("storage-driver-limit-concurrency", 16);
		config.val("storage-targetBucket-provision", false);
		config.val("item-data-size", "1KB");
		config.val("item-data-ranges-threshold", "512");
		config.val("item-output-path", "/bucket");
		final List<String> seedItems = new ArrayList<>();
		for (int i = 0; i < 20; i++) {
			seedItems.add(new DataItemImpl("/bucket/seed-" + i, 0, i % 2 == 0 ? SMALL : LARGE).toString());
		}
		config.val("item-input-file", Files.write(home.resolve("seeds.csv"), seedItems).toString());
		return config;
	}

	@SuppressWarnings({"rawtypes", "unchecked"
	})
	static final class Drivers implements StorageDriverFactory {

		static final String TYPE = "mixed-split-finish-mock";
		private static final long PARK_NANOS = TimeUnit.MILLISECONDS.toNanos(1);

		final boolean finishAtLastRange;
		final boolean lastRangeAtStop;
		final AtomicInteger admitted = new AtomicInteger();
		final AtomicInteger kickoffs = new AtomicInteger();
		final AtomicInteger rangeResults = new AtomicInteger();
		final AtomicInteger directFinishes = new AtomicInteger();
		final AtomicInteger queuedFinalizations = new AtomicInteger();
		final AtomicBoolean lastRangeAfterStop = new AtomicBoolean();
		private final AtomicReference<StorageDriver<?, ?>> created = new AtomicReference<>();

		Drivers(final boolean finishAtLastRange, final boolean lastRangeAtStop) {
			this.finishAtLastRange = finishAtLastRange;
			this.lastRangeAtStop = lastRangeAtStop;
		}

		OperationLifecycleCounters counters() {
			return created.get().operationLifecycle().counters();
		}

		@Override
		public String id() {
			return TYPE;
		}

		@Override
		public SchemaProvider schemaProvider() {
			return null;
		}

		@Override
		public void install(final Path dstPath) {}

		@Override
		public Config defaults(final Path appHomePath) {
			return null;
		}

		@Override
		public StorageDriver create(
						final String stepId, final DataInput dataInput, final Config storageConfig, final boolean verifyFlag,
						final int batchSize) {
			final StorageDriver driver = new CoopStorageDriverMock(stepId, dataInput, storageConfig, verifyFlag, batchSize) {

				private final AtomicInteger flatsAdmitted = new AtomicInteger();
				private final AtomicInteger compositesAdmitted = new AtomicInteger();
				private final AtomicInteger flatsSubmitted = new AtomicInteger();
				private final AtomicReference<Operation> heldRange = new AtomicReference<>();

				@Override
				protected boolean offerIncomingOperationLocked(final Operation op, final BlockingQueue queue) {
					if (op.type() != OpType.READ) {
						return false;
					}
					if (op instanceof CompositeOperation) {
						if (flatsAdmitted.get() < 1 || compositesAdmitted.get() >= 1) {
							return false;
						}
						if (!super.offerIncomingOperationLocked(op, queue)) {
							return false;
						}
						compositesAdmitted.incrementAndGet();
					} else {
						if (flatsAdmitted.get() != 0 || !super.offerIncomingOperationLocked(op, queue)) {
							return false;
						}
						flatsAdmitted.incrementAndGet();
					}
					admitted.incrementAndGet();
					return true;
				}

				@Override
				protected boolean finishCompositeRead(final Operation compositeRead) {
					if (!finishAtLastRange) {
						return false;
					}
					compositeRead.status(Operation.Status.SUCC);
					directFinishes.incrementAndGet();
					handleCompleted(compositeRead);
					return true;
				}

				@Override
				protected void onAdmissionClosed() {
					final Operation range = heldRange.getAndSet(null);
					if (range != null) {
						lastRangeAfterStop.set(!isAdmissionOpen());
						range.startRequest();
						range.finishRequest();
						range.startResponse();
						range.finishResponse();
						range.status(Operation.Status.SUCC);
						rangeResults.incrementAndGet();
						handleCompleted(range);
					}
				}

				@Override
				protected boolean submit(final Operation op) {
					if (op instanceof PartialOperation range) {
						if (lastRangeAtStop && range.partNumber() == 1) {
							// Sent, and answered only once the stop has closed admission.
							if (!beginDispatch(op)) {
								return false;
							}
							heldRange.set(op);
							return true;
						}
						final boolean sent = super.submit(op);
						if (sent) {
							rangeResults.incrementAndGet();
						}
						return sent;
					}
					if (op instanceof CompositeOperation composite) {
						if (composite.allSubOperationsDone()) {
							if (!beginDispatch(op)) {
								return false;
							}
							op.status(Operation.Status.SUCC);
							queuedFinalizations.incrementAndGet();
							handleCompleted(op);
							return true;
						}
						final boolean sent = super.submit(op);
						if (sent) {
							kickoffs.incrementAndGet();
						}
						return sent;
					}
					if (flatsSubmitted.get() == 0 && op.item() instanceof DataItem item && sizeOf(item) == SMALL) {
						if (!beginDispatch(op)) {
							return false;
						}
						flatsSubmitted.incrementAndGet();
						return true;
					}
					LockSupport.parkNanos(PARK_NANOS);
					return false;
				}

				@Override
				protected int submit(final List ops, final int from, final int to) {
					var i = from;
					while (i < to && submit((Operation) ops.get(i))) {
						i++;
					}
					return i - from;
				}
			};
			created.set(driver);
			return driver;
		}

		private static long sizeOf(final DataItem item) {
			try {
				return item.size();
			} catch (final IOException e) {
				return -1;
			}
		}
	}
}
