package com.dell.spt.load.step.mixed;

import static org.junit.jupiter.api.Assertions.assertInstanceOf;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.anyBoolean;
import static org.mockito.ArgumentMatchers.anyInt;
import static org.mockito.ArgumentMatchers.anyString;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.when;

import com.dell.spt.base.config.ConfigFormat;
import com.dell.spt.base.config.ConfigUtil;
import com.dell.spt.base.config.IllegalConfigurationException;
import com.dell.spt.base.config.InitialConfigSchemaProvider;
import com.dell.spt.base.metrics.MetricsManager;
import com.dell.spt.base.storage.driver.StorageDriverFactory;
import com.dell.spt.base.storage.driver.mock.DummyStorageDriverMock;
import com.github.akurilov.confuse.Config;
import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Path;
import java.util.List;
import java.util.UUID;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

/** A mixed step whose context is refused closes the driver it had already built. */
@SuppressWarnings({"rawtypes", "unchecked"
})
class MixedLoadStepLocalFailedInitTest {

	@TempDir
	Path home;

	@Test
	void aContextRefusedForItsRetryLimitClosesTheDriver() throws Exception {
		final Config config = defaultConfig();
		config.val("load-step-id", "mixed-failed-init-" + UUID.randomUUID());
		config.val("load-step-idAutoGenerated", false);
		config.val("storage-driver-type", "stub");
		config.val("load-op-weights-get", 0);
		config.val("load-op-weights-stat", 0);
		config.val("load-op-weights-put", 50);
		config.val("load-op-weights-delete", 50);
		config.val("load-op-retry", true);
		config.val("load-op-retryLimit", -1);
		config.val("item-output-file", home.resolve("put-remaining.csv").toString());
		final var driver = new DummyStorageDriverMock(config.configVal("storage"));
		final StorageDriverFactory factory = mock(StorageDriverFactory.class);
		when(factory.id()).thenReturn("stub");
		when(factory.create(anyString(), any(), any(), anyBoolean(), anyInt())).thenReturn(driver);
		final var step = new MixedLoadStepLocal(config, List.of(factory), List.of(), mock(MetricsManager.class));
		try {
			final var failure = assertThrows(IllegalConfigurationException.class, step::init);

			assertTrue(failure.getMessage().contains("load-op-retryLimit"), failure.toString());
			assertInstanceOf(DummyStorageDriverMock.class, driver);
			assertTrue(driver.isClosed());
		} finally {
			step.close();
		}
	}

	private static Config defaultConfig() throws Exception {
		final Config core = ConfigUtil.loadConfig(
						resource("/config/defaults.yaml"), ConfigFormat.YAML, InitialConfigSchemaProvider.provider().schema());
		final Config mixed = ConfigUtil.loadConfig(
						resource("/config/defaults-load-op-mixed.yaml"),
						ConfigFormat.YAML,
						new MixedLoadStepExtension().schemaProvider().schema());
		return ConfigUtil.merge(core.pathSep(), List.of(mixed, core));
	}

	private static String resource(final String name) throws IOException {
		try (InputStream stream = MixedLoadStepLocalFailedInitTest.class.getResourceAsStream(name)) {
			return new String(stream.readAllBytes(), StandardCharsets.UTF_8);
		}
	}
}
