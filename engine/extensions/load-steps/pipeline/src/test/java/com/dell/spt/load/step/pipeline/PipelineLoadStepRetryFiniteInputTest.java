/**
 * With {@code load-op-retry} on, a pipeline stage that has read everything the previous stage handed
 * over closes its Steady-State Window then. The driver delays every result, so the stage's last
 * operations are still running and the stop path cannot close the window first.
 */
@Timeout(120)
class PipelineLoadStepRetryFiniteInputTest {

	private static final int ITEMS = 20;
	private static final long RESULT_DELAY_MILLIS = 300;
	private static final String DRIVER_ID = "delayed-results-mock";

	private final ScheduledExecutorService results = Executors.newSingleThreadScheduledExecutor(
					Thread.ofPlatform().daemon().name("delayed-results").factory());

	@TempDir
	Path home;

	@BeforeEach
	void setHome() {
		ThreadContext.put("home_dir", home.toString());
	}

	@AfterEach
	void clearHome() {
		results.shutdownNow();
		ServiceUtil.shutdown();
		ThreadContext.remove("home_dir");
	}

	@Test
	void aStageClosesItsWindowWhenItsHandoffIsExhausted() throws Exception {
		final Config config = defaultConfig();
		config.val("load-step-id", "pipeline-retry-finite-" + UUID.randomUUID());
		config.val("load-step-idAutoGenerated", false);
		config.val("load-step-limit-time", "30s");
		config.val("storage-driver-type", DRIVER_ID);
		config.val("storage-driver-limit-concurrency", 4);
		config.val("storage-targetBucket-provision", false);
		config.val("output-metrics-timing-persist", false);
		config.val("output-metrics-trace-persist", false);
		config.val("item-data-size", "1KB");
		config.val("item-data-verify", false);
		config.val("item-output-path", "/bucket");
		config.val("load-op-retry", true);
		final ContextRecordingMetrics metrics = new ContextRecordingMetrics();
		final List<Extension> extensions = List.of(new PipelineLoadStepExtension(), new DelayedResultsDriverExtension());

		assertTimeoutPreemptively(Duration.ofSeconds(60), () -> new PipelineLoadStepClient(config, extensions, null, metrics)
						.append(Map.of("load", Map.of("op", Map.of("limit", Map.of("count", ITEMS)))))
						.append(Map.of("load", Map.of("op", Map.of("type", "read"))))
						.run());

		final MetricsContext<?> read = metrics.contexts.get(OpType.READ);
		assertEquals(ITEMS, read.lastSnapshot().successSnapshot().count());
		assertEquals("scheduling exhaustion", read.steadyResult().cause(), read.steadyResult().toString());
	}

	/** Keeps each local context, since the manager's terminal entries hold one per step. */
	private static final class ContextRecordingMetrics extends MetricsManagerImpl {
		final Map<OpType, MetricsContext<?>> contexts = new ConcurrentHashMap<>();

		ContextRecordingMetrics() {
			super(ServiceTaskExecutor.VT_EXECUTOR);
		}

		@Override
		public void unregister(final MetricsContext metricsCtx) {
			super.unregister(metricsCtx);
			if (!(metricsCtx instanceof DistributedMetricsContext)) {
				contexts.put(metricsCtx.opType(), metricsCtx);
			}
		}
	}

	/** The dummy mock driver, with each operation's result delivered after a delay. */
	private final class DelayedResultsDriverExtension extends ExtensionBase
					implements StorageDriverFactory<DataItem, Operation<DataItem>, StorageDriver<DataItem, Operation<DataItem>>> {

		@Override
		public String id() {
			return DRIVER_ID;
		}

		@Override
		@SuppressWarnings("unchecked")
		public StorageDriver<DataItem, Operation<DataItem>> create(
						final String stepId,
						final DataInput dataInput,
						final Config storageConfig,
						final boolean verifyFlag,
						final int batchSize) {
			final StorageDriver<DataItem, Operation<DataItem>> driver = DummyStorageDriverMock.create(
							storageConfig.intVal("driver-limit-concurrency"));
			return (StorageDriver<DataItem, Operation<DataItem>>) Proxy.newProxyInstance(
							StorageDriver.class.getClassLoader(),
							new Class<?>[]{StorageDriver.class
							},
							(proxy, method, args) -> {
								final boolean resultOutput = method.getName().equals("operationResultOutput");
								final Object[] actualArgs = resultOutput
												? new Object[]{new DelayedOutput((Output<Operation<DataItem>>) args[0])
								}
												: args;
								try {
									return method.invoke(driver, actualArgs);
								} catch (final InvocationTargetException e) {
									throw e.getCause();
								}
							});
		}

		@Override
		public SchemaProvider schemaProvider() {
			return null;
		}

		@Override
		protected String defaultsFileName() {
			return null;
		}

		@Override
		protected List<String> resourceFilesToInstall() {
			return List.of();
		}
	}

	private final class DelayedOutput implements Output<Operation<DataItem>> {
		private final Output<Operation<DataItem>> target;

		DelayedOutput(final Output<Operation<DataItem>> target) {
			this.target = target;
		}

		@Override
		public boolean put(final Operation<DataItem> op) {
			final var unused = results.schedule(() -> target.put(op), RESULT_DELAY_MILLIS, TimeUnit.MILLISECONDS);
			return true;
		}

		@Override
		public int put(final List<Operation<DataItem>> ops, final int from, final int to) {
			throw new AssertionError("the dummy mock driver hands over one result at a time");
		}

		@Override
		public int put(final List<Operation<DataItem>> ops) {
			throw new AssertionError("the dummy mock driver hands over one result at a time");
		}

		@Override
		public Input<Operation<DataItem>> getInput() {
			throw new AssertionError();
		}

		@Override
		public void close() {}
	}

	/** The shipped defaults of the engine and of this extension, as the engine merges them. */
	private static Config defaultConfig() throws Exception {
		final Config core = ConfigUtil.loadConfig(
						resource("/config/defaults.yaml"), ConfigFormat.YAML, InitialConfigSchemaProvider.provider().schema());
		final Config pipeline = ConfigUtil.loadConfig(
						resource("/config/defaults-item-output-delay.yaml"),
						ConfigFormat.YAML,
						new PipelineLoadStepExtension().schemaProvider().schema());
		return ConfigUtil.merge(core.pathSep(), List.of(pipeline, core));
	}

	private static String resource(final String name) throws IOException {
		try (InputStream stream = PipelineLoadStepRetryFiniteInputTest.class.getResourceAsStream(name)) {
			return new String(stream.readAllBytes(), StandardCharsets.UTF_8);
		}
	}
}
