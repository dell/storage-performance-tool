/**
 * The entry refuses a composite configuration of any sub-step before it reads an item input: a
 * READ base from a storage path at threshold 0, then a context at 0 and one at {@code 1MB}, sends
 * no listing request, and every driver the check built is closed.
 */
@SuppressWarnings({"rawtypes", "unchecked"
})
class PipelineCompositeRefusalBeforeListingTest {

	private static final Duration RUN_TIMEOUT = Duration.ofSeconds(60);

	private final AtomicInteger listings = new AtomicInteger();
	private final AtomicInteger created = new AtomicInteger();
	private final AtomicInteger closed = new AtomicInteger();

	@TempDir
	Path home;

	@BeforeEach
	void setHome() {
		ThreadContext.put("home_dir", home.toString());
	}

	@AfterEach
	void clearHome() {
		ThreadContext.remove("home_dir");
	}

	@Test
	void aRefusalInTheSecondContextListsNothing() throws Exception {
		try (var metrics = new MetricsManagerImpl(ServiceTaskExecutor.VT_EXECUTOR)) {
			final var client = client(metrics, "1MB");
			final var failure = assertTimeoutPreemptively(
							RUN_TIMEOUT, () -> assertThrows(RunTerminalException.class, client::run));
			assertEquals(IntegrityTerminalException.Category.CONFIGURATION, failure.category());
			assertTrue(failure.getMessage().contains("would make composite READ operations"), failure.getMessage());
			assertEquals(0, listings.get(), "no listing request before the refusal");
			assertTrue(created.get() > 0);
			assertEquals(created.get(), closed.get(), "every driver the check built is closed");
		}
	}

	@Test
	void theSameStepAtThresholdZeroEverywhereLists() throws Exception {
		try (var metrics = new MetricsManagerImpl(ServiceTaskExecutor.VT_EXECUTOR)) {
			final var client = client(metrics, 0);
			assertTimeoutPreemptively(RUN_TIMEOUT, () -> {
				try {
					client.run();
				} catch (final RuntimeException ignored) {
					// The empty listing leaves the step nothing to read; only the listing counts here.
				}
			});
			assertTrue(listings.get() > 0, "the probe sees the listing a refused step must not send");
		}
	}

	private PipelineLoadStepClient client(final MetricsManagerImpl metrics, final Object secondThreshold)
					throws Exception {
		final Config config = defaultConfig();
		config.val("load-step-id", "pipeline-composite-" + UUID.randomUUID());
		config.val("load-step-idAutoGenerated", false);
		config.val("load-step-limit-time", 0);
		config.val("load-op-type", "read");
		config.val("load-op-limit-count", 1L);
		config.val("storage-driver-type", "dummy-mock");
		config.val("storage-driver-limit-concurrency", 1);
		config.val("storage-targetBucket-provision", false);
		config.val("item-input-path", "/bucket");
		config.val("item-input-file", null);
		config.val("item-data-ranges-threshold", 0);
		final StorageDriverFactory factory = mock(StorageDriverFactory.class);
		when(factory.id()).thenReturn("dummy-mock");
		when(factory.create(anyString(), any(), any(), anyBoolean(), anyInt()))
						.thenAnswer(invocation -> probe(new DummyStorageDriverMock(invocation.getArgument(2))));
		final List<Extension> extensions = List.of(new PipelineLoadStepExtension(), factory);
		return new PipelineLoadStepClient(config, extensions, null, metrics)
						.append(Map.of("item", Map.of("data", Map.of("ranges", Map.of("threshold", 0)))))
						.append(Map.of("item", Map.of("data", Map.of("ranges", Map.of("threshold", secondThreshold)))));
	}

	/** A driver without composite support that records each listing and each close. */
	private StorageDriver probe(final StorageDriver target) {
		created.incrementAndGet();
		return (StorageDriver) Proxy.newProxyInstance(
						StorageDriver.class.getClassLoader(),
						new Class<?>[]{StorageDriver.class, CompositeOperationsUnsupported.class
						},
						(proxy, method, args) -> {
							if ("list".equals(method.getName())) {
								listings.incrementAndGet();
								return List.of();
							}
							if ("close".equals(method.getName()) && method.getParameterCount() == 0) {
								closed.incrementAndGet();
							}
							try {
								return method.invoke(target, args);
							} catch (final InvocationTargetException e) {
								throw e.getCause();
							}
						});
	}

	/** The shipped defaults of the engine and of this extension, as the engine merges them. */
	private static Config defaultConfig() throws Exception {
		final Config core = ConfigUtil.loadConfig(
						resource("/config/defaults.yaml"), ConfigFormat.YAML, InitialConfigSchemaProvider.provider().schema());
		final Config pipeline = ConfigUtil.loadConfig(
						resource("/config/defaults-item-output-delay.yaml"),
						ConfigFormat.YAML,
						new PipelineLoadStepExtension().schemaProvider().schema());
		return ConfigUtil.merge(core.pathSep(), List.of(pipeline, core));
	}

	private static String resource(final String name) throws IOException {
		try (InputStream stream = PipelineCompositeRefusalBeforeListingTest.class.getResourceAsStream(name)) {
			return new String(stream.readAllBytes(), StandardCharsets.UTF_8);
		}
	}
}
