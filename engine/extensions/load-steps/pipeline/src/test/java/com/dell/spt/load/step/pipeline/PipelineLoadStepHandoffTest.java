package com.dell.spt.load.step.pipeline;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTimeoutPreemptively;
import static org.junit.jupiter.api.Assertions.assertTrue;

import com.dell.spt.base.concurrent.ServiceTaskExecutor;
import com.dell.spt.base.config.ConfigFormat;
import com.dell.spt.base.config.ConfigUtil;
import com.dell.spt.base.config.InitialConfigSchemaProvider;
import com.dell.spt.base.env.Extension;
import com.dell.spt.base.metrics.MetricsManagerImpl;
import com.dell.spt.base.storage.driver.mock.DummyStorageDriverMockExtension;
import com.dell.spt.base.svc.ServiceUtil;
import com.github.akurilov.confuse.Config;
import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Duration;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.concurrent.atomic.AtomicInteger;
import org.apache.logging.log4j.ThreadContext;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

/**
 * The handoff from a pipeline step's writing context to its reading context: the reader reads every
 * item written, and ends when its writer ends.
 */
class PipelineLoadStepHandoffTest {

	/** Each run takes its own step ID: the engine's log routing keeps a step's files by its ID. */
	private static final AtomicInteger RUNS = new AtomicInteger();
	/** Smaller than a batch, so a writer's batch waits for the reader to make room. */
	private static final int QUEUE_LIMIT = 8;
	private static final int BATCH_SIZE = 32;

	@TempDir
	Path home;

	@BeforeEach
	void setHome() {
		ThreadContext.put("home_dir", home.toString());
	}

	@AfterEach
	void clearHome() {
		ThreadContext.remove("home_dir");
	}

	@Test
	void aReaderThatStartsBeforeTheFirstResultReadsEveryItemWrittenThroughASmallHandoff() throws Exception {
		final List<String> read = runCreateThenRead(Map.of("op", Map.of("limit", Map.of("count", 1_000))), "30s");

		assertEquals(1_000, read.size(), "the reader reads every item, after many fills of the handoff");
		assertEquals(read.size(), new HashSet<>(read).size(), "each item once");
	}

	@Test
	void aWriterSlowerThanItsReaderHandsOverEveryItem() throws Exception {
		final List<String> read = runCreateThenRead(
						Map.of("op", Map.of("limit", Map.of("count", 40, "rate", 40))), "30s");

		assertEquals(40, read.size(), "the reader waits through the writer's gaps for its end");
		assertEquals(read.size(), new HashSet<>(read).size());
	}

	@Test
	void aStepStoppedWhileItsWriterStillWritesEndsAndItsReaderReadsWhatWasHandedOver() throws Exception {
		final long started = System.nanoTime();
		final List<String> read = runCreateThenRead(Map.of("op", Map.of("limit", Map.of("rate", 20))), "2s");
		final Duration took = Duration.ofNanos(System.nanoTime() - started);

		assertTrue(took.compareTo(Duration.ofSeconds(15)) < 0, "the step ends soon after its limit: " + took);
		// About 40 items in 2 s at 20 per second; the rest of the bound covers the step's start.
		assertTrue(0 < read.size() && read.size() <= 100, read.size() + " items read");
		assertEquals(read.size(), new HashSet<>(read).size());
	}

	/**
	 * Runs a step whose first context creates items with the given {@code load} settings and whose
	 * second reads them from the handoff. Returns the items the reader lists in its item output.
	 */
	private List<String> runCreateThenRead(final Map<String, Object> writerLoad, final String stepTimeLimit)
					throws Exception {
		final Path readItems = home.resolve("read.csv");
		final List<Extension> extensions = List.of(new PipelineLoadStepExtension(), new DummyStorageDriverMockExtension<>());
		final Config config = defaultConfig();
		config.val("load-step-id", "pipeline-handoff-" + RUNS.incrementAndGet());
		config.val("load-step-idAutoGenerated", false);
		config.val("load-step-limit-time", stepTimeLimit);
		config.val("load-batch-size", BATCH_SIZE);
		config.val("storage-driver-limit-concurrency", 4);
		config.val("storage-targetBucket-provision", false);
		config.val("item-data-size", "1KB");
		config.val("item-output-path", "/bucket");
		config.val("item-output-queue-limit", QUEUE_LIMIT);
		try {
			assertTimeoutPreemptively(Duration.ofSeconds(60), () -> new PipelineLoadStepClient(
							config, extensions, null, new MetricsManagerImpl(ServiceTaskExecutor.VT_EXECUTOR))
							.append(Map.of("load", writerLoad))
							.append(Map.of(
											"load", Map.of("op", Map.of("type", "read")),
											"item", Map.of("output", Map.of("file", readItems.toString()))))
							.run());
		} finally {
			ServiceUtil.shutdown();
		}
		return Files.readAllLines(readItems, StandardCharsets.UTF_8).stream()
						.map(line -> line.split(",", 2)[0])
						.toList();
	}

	/** The shipped defaults of the engine and of this extension, as the engine merges them. */
	private static Config defaultConfig() throws Exception {
		final Config core = ConfigUtil.loadConfig(
						resource("/config/defaults.yaml"), ConfigFormat.YAML, InitialConfigSchemaProvider.provider().schema());
		final Config pipeline = ConfigUtil.loadConfig(
						resource("/config/defaults-item-output-delay.yaml"),
						ConfigFormat.YAML,
						new PipelineLoadStepExtension().schemaProvider().schema());
		return ConfigUtil.merge(core.pathSep(), List.of(pipeline, core));
	}

	private static String resource(final String name) throws IOException {
		try (InputStream stream = PipelineLoadStepHandoffTest.class.getResourceAsStream(name)) {
			return new String(stream.readAllBytes(), StandardCharsets.UTF_8);
		}
	}
}
