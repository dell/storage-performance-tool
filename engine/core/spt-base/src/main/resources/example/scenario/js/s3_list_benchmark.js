function envOrDefault(name, defaultValue) {
	var value = java.lang.System.getenv(name);
	return value == null || value.length() == 0 ? defaultValue : String(value);
}

var CONCURRENCY = java.lang.Integer.parseInt(envOrDefault("LIST_CONCURRENCY", "128"));
var BUCKET_NAME = envOrDefault("S3_BUCKET", "my-bucket");
var LIST_PREFIX = envOrDefault("LIST_PREFIX", "");
var DURATION = envOrDefault("LIST_DURATION", "0"); // ISO-8601 or seconds
var OBJECT_LIMIT = java.lang.Long.parseLong(envOrDefault("LIST_OBJECT_LIMIT", "0"));

var ENDPOINT = envOrDefault("S3_ENDPOINT", "s3.amazonaws.com");
var REGION = envOrDefault("S3_REGION", "us-east-1");
var ACCESS_KEY = envOrDefault("S3_ACCESS_KEY", "");
var SECRET_KEY = envOrDefault("S3_SECRET_KEY", "");
var SESSION_TOKEN = envOrDefault("S3_SESSION_TOKEN", "");

var FETCH_METADATA = java.lang.Boolean.parseBoolean(envOrDefault("LIST_FETCH_METADATA", "false"));
var INCLUDE_VERSIONS = java.lang.Boolean.parseBoolean(envOrDefault("LIST_INCLUDE_VERSIONS", "false"));
var DELIMITER = envOrDefault("LIST_DELIMITER", "/");
var MAX_KEYS = java.lang.Integer.parseInt(envOrDefault("LIST_PAGE_SIZE", "1000"));
var SHARDING_MODE = envOrDefault("LIST_SHARDING_MODE", "none");
var SHARDING_RADIX = java.lang.Integer.parseInt(envOrDefault("LIST_SHARDING_RADIX", "0"));
var SHARDING_CHARSET = envOrDefault("LIST_SHARDING_CHARSET", "0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ");

var bucketPath = "/" + BUCKET_NAME;
var listLimit = OBJECT_LIMIT > 0 ? { count: OBJECT_LIMIT, rate: 0 } : { rate: 0 };

var config = {
storage: {
	region: REGION,
	driver: {
	type: "s3",
	limit: { concurrency: CONCURRENCY }
	},
	net: {
	node: { addrs: [ENDPOINT], port: 443 },
	ssl: { enabled: true }
	},
	auth: {
	uid: ACCESS_KEY,
	secret: SECRET_KEY,
	token: SESSION_TOKEN,
	version: 4
	}
},
item: {
	type: "path",
	input: { path: bucketPath },
	naming: {
	radix: 36,
	prefix: LIST_PREFIX,
	type: "random"
	}
},
load: {
	batch: { size: MAX_KEYS },
	op: {
	type: "list",
	list: {
		delimiter: DELIMITER,
		fetch_metadata: FETCH_METADATA,
		include_versions: INCLUDE_VERSIONS,
		max_keys: MAX_KEYS,
		sharding: {
			mode: SHARDING_MODE,
			radix: SHARDING_RADIX,
			charset: SHARDING_CHARSET
		}
	},
	limit: listLimit,
	wait: { finish: true }
	},
	step: {
	idAutoGenerated: true
	}
},
output: {
	metrics: {
	summary: { persist: true },
	average: { period: "5s" }
	}
}
};

if (DURATION !== "0") {
	config.load.step.limit = { time: DURATION };
}

var step = Load.config(config).start();
step.await();
step.close();
