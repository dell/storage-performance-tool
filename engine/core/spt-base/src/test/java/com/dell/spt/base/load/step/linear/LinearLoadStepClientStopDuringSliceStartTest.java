/**
 * The shutdown hook stops a distributed step whose first remote slice has started while the next
 * node is still being set up. The client step, its slices and the RMI transfer are the real ones;
 * both nodes run in this JVM, and the second holds its step manager call until the test lets go.
 */
@Timeout(120)
class LinearLoadStepClientStopDuringSliceStartTest {

	private static final long WAIT_SECONDS = 30;
	private static final String RMI_HOSTNAME = "java.rmi.server.hostname";

	private final Config config = TestConfigBuilder.config();
	private final MetricsManagerImpl entryMgr = new MetricsManagerImpl(ServiceTaskExecutor.VT_EXECUTOR);
	private final MetricsManagerImpl workerMgr = new MetricsManagerImpl(ServiceTaskExecutor.VT_EXECUTOR);
	private final List<String> closeFailures = new ArrayList<>();
	private final Handler closeFailureHandler = new Handler() {
		@Override
		public void publish(final LogRecord record) {
			synchronized (closeFailures) {
				closeFailures.add(record.getMessage() + ": " + record.getThrown());
			}
		}

		@Override
		public void flush() {}

		@Override
		public void close() {}
	};
	private String originalRmiHostname;
	private FileManagerServiceImpl liveFiles;
	private LoadStepManagerServiceImpl liveManager;
	private FileManagerServiceImpl heldFiles;
	private HeldStepManager heldManager;
	private LinearLoadStepClient client;

	@BeforeEach
	void startTheNodes() throws Exception {
		originalRmiHostname = System.getProperty(RMI_HOSTNAME);
		System.setProperty(RMI_HOSTNAME, "127.0.0.1");
		final int livePort = freePort();
		final int heldPort = freePort();
		liveFiles = new FileManagerServiceImpl(livePort);
		liveFiles.start();
		liveManager = new LoadStepManagerServiceImpl(livePort, extensions(), workerMgr);
		liveManager.start();
		heldFiles = new FileManagerServiceImpl(heldPort);
		heldFiles.start();
		heldManager = new HeldStepManager(heldPort);
		heldManager.start();
		// Daemons earlier tests left open would fail their closes in this test's closeAll.
		DaemonBase.closeAll();
		Logger.getLogger(DaemonBase.class.getSimpleName()).addHandler(closeFailureHandler);

		config.val("load-step-id", "stop-during-slice-start-" + System.nanoTime());
		config.val("load-step-idAutoGenerated", false);
		config.val("load-step-node-addrs", List.of("127.0.0.1:" + livePort, "127.0.0.1:" + heldPort));
		config.val("output-metrics-timing-persist", false);
		config.val("output-metrics-trace-persist", false);
		config.val("output-metrics-summary-persist", false);
		config.val("item-data-input-compressibility", 0.0);
		config.val("item-data-dedupable", false);
		config.val("item-data-verify", false);
		config.val("item-data-ranges-concat", null);
		config.val("item-input-file", null);
		config.val("item-input-path", null);
		config.val("load-op-type", "noop");
		config.val("load-op-limit-count", 0);
		config.val("load-step-limit-time", "10m");
		config.val("load-op-wait-finish", true);
		config.val("load-op-wait-limit", 1);
	}

	@AfterEach
	void closeTheNodes() throws Exception {
		JvmExitTestSupport.reset();
		Logger.getLogger(DaemonBase.class.getSimpleName()).removeHandler(closeFailureHandler);
		heldManager.release.countDown();
		try {
			if (client != null && !client.isClosed()) {
				client.close();
			}
			heldManager.close();
			heldFiles.close();
			liveManager.close();
			liveFiles.close();
		} finally {
			ServiceUtil.shutdown();
			if (originalRmiHostname == null) {
				System.clearProperty(RMI_HOSTNAME);
			} else {
				System.setProperty(RMI_HOSTNAME, originalRmiHostname);
			}
		}
	}

	@Test
	void theExitStopsTheStartAndClosesTheSliceAlreadyStarted() throws Exception {
		client = new LinearLoadStepClient(config, extensions(), List.of(), entryMgr);
		final var runOutcome = new AtomicReference<Throwable>();
		final var runThread = new Thread(() -> {
			try {
				client.run();
			} catch (final Throwable e) {
				runOutcome.set(e);
			}
		}, "stop-during-slice-start-run");
		runThread.setDaemon(true);
		runThread.start();
		assertTrue(heldManager.entered.await(WAIT_SECONDS, TimeUnit.SECONDS), "the step did not reach the second node");
		final LoadStepService startedSlice = liveManager.getStepService();
		assertNotNull(startedSlice, "the first node's slice must exist before the stop");
		assertTrue(startedSlice.isStarted(), "the first node's slice must have started before the stop");

		// As the shutdown hook does
		JvmExit.markBegun();
		final var hook = new Thread(DaemonBase::closeAll, "stop-during-slice-start-hook");
		hook.setDaemon(true);
		hook.start();
		// An RMI call does not end on an interrupt; it returns when the node answers.
		final long deadline = System.nanoTime() + TimeUnit.SECONDS.toNanos(WAIT_SECONDS);
		while (!runThread.isInterrupted()) {
			assertTrue(System.nanoTime() < deadline, "the hook did not interrupt the starting thread");
			Thread.sleep(10);
		}
		heldManager.release.countDown();
		runThread.join(TimeUnit.SECONDS.toMillis(WAIT_SECONDS));
		hook.join(TimeUnit.SECONDS.toMillis(WAIT_SECONDS));

		assertFalse(runThread.isAlive(), "the run did not end");
		assertFalse(hook.isAlive(), "closeAll did not end");
		assertInstanceOf(InterruptedException.class, runOutcome.get());
		assertTrue(client.isClosed());
		assertTrue(startedSlice.isClosed(), "the slice started before the stop stayed open: " + startedSlice.state());
		synchronized (closeFailures) {
			assertEquals(List.of(), closeFailures);
		}
	}

	private static int freePort() throws Exception {
		try (ServerSocket socket = new ServerSocket(0)) {
			socket.setReuseAddress(true);
			return socket.getLocalPort();
		}
	}

	private static List<Extension> extensions() {
		return List.of(new LinearLoadStepExtension<>(), new DummyStorageDriverMockExtension<>());
	}

	/** A node's step manager that answers its first call only when released, and then with a refusal. */
	private static final class HeldStepManager extends ServiceBase implements LoadStepManagerService {

		private final CountDownLatch entered = new CountDownLatch(1);
		private final CountDownLatch release = new CountDownLatch(1);

		private HeldStepManager(final int port) {
			super(port);
		}

		@Override
		public String name() {
			return SVC_NAME;
		}

		@Override
		public String newStepService(final String stepType, final Config config, final List<Config> ctxConfigs)
						throws RemoteException {
			entered.countDown();
			try {
				release.await(2 * WAIT_SECONDS, TimeUnit.SECONDS);
			} catch (final InterruptedException e) {
				Thread.currentThread().interrupt();
			}
			throw new RemoteException("the node is going away");
		}

		@Override
		public LoadStepService getStepService() {
			return null;
		}

		// The node refuses its only step, so it never holds a slice.
		@Override
		public List<Long> busySliceRunIds() {
			return List.of();
		}

		@Override
		public boolean hasOpenSlices() {
			return false;
		}

		@Override
		public boolean stopSlicesOfRun(final long runId) {
			return false;
		}
	}
}
