import org.junit.jupiter.api.Timeout;

/**
 * Which storage driver statistics a distributed linear step keeps on its Entry Node when it ends.
 *
 * <p>The client step, both of its slices, their metrics contexts, the metrics aggregator, both
 * metrics managers and the transfer between Engine Participants (RMI over the loopback interface)
 * are the real ones; only the storage drivers are test drivers that count for themselves. The
 * second slice runs behind the services of a second Engine Participant in this JVM, which has a
 * metrics manager of its own.
 */
@Timeout(120)
class LinearLoadStepClientDriverStatsTerminalTest {

	private static final long WAIT_MILLIS = 20_000;
	private static final String RMI_HOSTNAME = "java.rmi.server.hostname";

	private final Config config = TestConfigBuilder.config();
	private final MetricsManagerImpl entryMgr = new MetricsManagerImpl(ServiceTaskExecutor.VT_EXECUTOR);
	private final MetricsManagerImpl workerMgr = new MetricsManagerImpl(ServiceTaskExecutor.VT_EXECUTOR);
	// Of the 7 operations each slice gets, the Entry Node's driver answers 3 and the worker's answers 2.
	private final StatsReportingDriverMock.Extension<DataItem, Operation<DataItem>> entryDrivers = new StatsReportingDriverMock.Extension<>(3);
	private final StatsReportingDriverMock.Extension<DataItem, Operation<DataItem>> workerDrivers = new StatsReportingDriverMock.Extension<>(2);
	private String originalRmiHostname;
	private FileManagerServiceImpl fileService;
	private LoadStepManagerServiceImpl stepManager;
	private LinearLoadStepClient client;

	@BeforeEach
	void startTheWorker() throws Exception {
		entryMgr.setTerminalRetentionMillis(30_000);
		workerMgr.setTerminalRetentionMillis(30_000);
		final int port;
		try (ServerSocket socket = new ServerSocket(0)) {
			socket.setReuseAddress(true);
			port = socket.getLocalPort();
		}
		originalRmiHostname = System.getProperty(RMI_HOSTNAME);
		System.setProperty(RMI_HOSTNAME, "127.0.0.1");
		fileService = new FileManagerServiceImpl(port);
		fileService.start();
		stepManager = new LoadStepManagerServiceImpl(port, extensions(workerDrivers), workerMgr);
		stepManager.start();

		config.val("load-step-id", "driver-stats-fleet-" + System.nanoTime());
		config.val("load-step-idAutoGenerated", false);
		config.val("load-step-node-addrs", List.of("127.0.0.1:" + port));
		config.val("storage-driver-type", StatsReportingDriverMock.DRIVER);
		config.val("output-metrics-timing-persist", false);
		config.val("output-metrics-trace-persist", false);
		config.val("item-data-input-compressibility", 0.0);
		config.val("item-data-dedupable", false);
		config.val("item-data-verify", false);
		config.val("item-data-ranges-concat", null);
		// New items, and an operation type that leaves no artifact for the step to merge when it closes:
		// the two participants of this test share one file system.
		config.val("item-input-file", null);
		config.val("item-input-path", null);
		config.val("load-op-type", "noop");
		// 7 operations for each of the two slices; the ones in flight get 1 second when the step stops.
		config.val("load-op-limit-count", 14);
		config.val("load-op-wait-finish", true);
		config.val("load-op-wait-limit", 1);
	}

	@AfterEach
	void closeAll() throws Exception {
		try {
			if (client != null && !client.isClosed()) {
				client.close();
			}
			if (stepManager != null && !stepManager.isClosed()) {
				stepManager.close();
			}
			if (fileService != null && !fileService.isClosed()) {
				fileService.close();
			}
		} finally {
			ServiceUtil.shutdown();
			if (originalRmiHostname == null) {
				System.clearProperty(RMI_HOSTNAME);
			} else {
				System.setProperty(RMI_HOSTNAME, originalRmiHostname);
			}
		}
	}

	@Test
	void stoppedStepKeepsTheSumOfWhatEachContributorsDriverCountedBeforeItClosed() throws Exception {
		final DriverStatsSnapshot entryFinal = StatsReportingDriverMock.stats(7, 3, 4);
		final DriverStatsSnapshot workerFinal = StatsReportingDriverMock.stats(7, 2, 5);
		final DriverStatsSnapshot sum = StatsReportingDriverMock.stats(14, 5, 9);
		client = new LinearLoadStepClient(config, extensions(entryDrivers), List.of(), entryMgr);
		client.start();
		assertTrue(client.isStarted(), "the step must start: " + client.state());
		final SelfCounting<DataItem, Operation<DataItem>> entryDriver = sliceDriver(entryDrivers);
		final SelfCounting<DataItem, Operation<DataItem>> workerDriver = sliceDriver(workerDrivers);
		await(
						() -> entryFinal.equals(entryDriver.currentStats()) && workerFinal.equals(workerDriver.currentStats()),
						() -> "entry " + entryDriver.currentStats() + ", worker " + workerDriver.currentStats());

		// While the step runs, the Entry Node totals what both contributors report.
		final DistributedMetricsContext<?> fleet = onlyFleetContext();
		await(
						() -> {
							final DriverStatsTotal live = liveTotal(fleet);
							return live != null && sum.equals(live.sum());
						},
						() -> "live total " + liveTotal(fleet));
		assertEquals(2, liveTotal(fleet).reporting());
		assertFalse(liveTotal(fleet).partial());

		client.stop();

		final TerminalStepEntry entryNode = entry(entryMgr, false);
		final TerminalStepEntry workerNode = entry(workerMgr, false);
		final TerminalStepEntry fleetEntry = entry(entryMgr, true);
		assertEquals(entryFinal, entryNode.driverStats);
		assertEquals(workerFinal, workerNode.driverStats);
		assertReportedWhenStopped(entryDriver, entryNode);
		assertReportedWhenStopped(workerDriver, workerNode);
		assertEquals(
						DriverStatsTotal.of(List.of(entryNode.driverStats, workerNode.driverStats), true),
						fleetEntry.driverStatsTotal,
						"the fleet keeps the sum of what each contributor kept");
		assertEquals(sum, fleetEntry.driverStatsTotal.sum());
		assertEquals(2, fleetEntry.driverStatsTotal.reporting());
		assertFalse(fleetEntry.driverStatsTotal.partial());
		assertNull(fleetEntry.driverStats);
		assertNull(entryNode.driverStatsTotal);
		assertEquals(5, fleetEntry.successCount);
		assertEquals(2, fleetEntry.nodeCount);
		assertFalse(fleetEntry.partial);
		assertEquals(1, workerMgr.getTerminalSteps().size(), workerMgr.getTerminalSteps().toString());

		client.close();

		// The closed drivers hold nothing; the fleet keeps the levels from before they closed.
		assertEquals(StatsReportingDriverMock.stats(7, 3, 0), entryDriver.currentStats());
		assertEquals(StatsReportingDriverMock.stats(7, 2, 0), workerDriver.currentStats());
		assertEquals(sum, entry(entryMgr, true).driverStatsTotal.sum());
	}

	private static List<Extension> extensions(
					final StatsReportingDriverMock.Extension<DataItem, Operation<DataItem>> drivers) {
		return List.of(new LinearLoadStepExtension<>(), drivers, new DummyStorageDriverMockExtension<>());
	}

	/**
	 * The driver of a participant's slice: the last one created there. The client step creates one
	 * before it, to look for an item input, and closes that one without starting it.
	 */
	@SuppressWarnings("unchecked")
	private static SelfCounting<DataItem, Operation<DataItem>> sliceDriver(
					final StatsReportingDriverMock.Extension<DataItem, Operation<DataItem>> drivers) {
		final var created = drivers.created();
		return (SelfCounting<DataItem, Operation<DataItem>>) created.get(created.size() - 1);
	}

	private DistributedMetricsContext<?> onlyFleetContext() {
		@SuppressWarnings("rawtypes")
		final Set<DistributedMetricsContext> fleets = entryMgr.getDistributedContexts();
		assertEquals(1, fleets.size(), fleets.toString());
		return fleets.iterator().next();
	}

	private static DriverStatsTotal liveTotal(final DistributedMetricsContext<?> fleet) {
		fleet.refreshLastSnapshot();
		final DistributedAllMetricsSnapshot snapshot = fleet.lastSnapshot();
		return snapshot == null ? null : snapshot.driverStatsTotal();
	}

	/** The one entry a metrics manager kept for the step: its fleet's or its node's. */
	private static TerminalStepEntry entry(final MetricsManagerImpl mgr, final boolean distributed) {
		final List<TerminalStepEntry> entries = mgr.getTerminalSteps().stream()
						.filter(entry -> entry.distributed == distributed)
						.toList();
		assertEquals(1, entries.size(), mgr.getTerminalSteps().toString());
		return entries.get(0);
	}

	/** The entry holds the driver's last answer, and that answer came from the stopped driver. */
	private static void assertReportedWhenStopped(
					final SelfCounting<DataItem, Operation<DataItem>> driver, final TerminalStepEntry entry) {
		final List<SelfCounting.Answer> answers = driver.answers();
		final SelfCounting.Answer last = answers.get(answers.size() - 1);
		assertEquals(AsyncRunnable.State.STOPPED, last.state(), answers.toString());
		assertEquals(last.stats(), entry.driverStats);
	}

	private static void await(final BooleanSupplier condition, final Supplier<String> reached)
					throws InterruptedException {
		final long deadline = System.nanoTime() + TimeUnit.MILLISECONDS.toNanos(WAIT_MILLIS);
		while (!condition.getAsBoolean()) {
			assertTrue(System.nanoTime() < deadline, () -> "not reached in " + WAIT_MILLIS + " ms: " + reached.get());
			Thread.sleep(10);
		}
	}
}
