package com.dell.spt.base.load.step.local;

import static com.dell.spt.base.load.step.local.SteadyLifecycleSupport.createStepConfig;
import static com.dell.spt.base.load.step.local.SteadyLifecycleSupport.steadySettings;
import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTimeoutPreemptively;

import com.dell.spt.base.concurrent.ServiceTaskExecutor;
import com.dell.spt.base.env.Extension;
import com.dell.spt.base.load.step.linear.LinearLoadStepClient;
import com.dell.spt.base.load.step.linear.LinearLoadStepExtension;
import com.dell.spt.base.load.step.local.SteadyLifecycleSupport.LatencyDriverExtension;
import com.dell.spt.base.load.step.service.LoadStepManagerServiceImpl;
import com.dell.spt.base.load.step.service.file.FileManagerServiceImpl;
import com.dell.spt.base.metrics.MetricsManagerImpl;
import com.dell.spt.base.metrics.TerminalStepEntry;
import com.dell.spt.base.svc.ServiceUtil;
import com.github.akurilov.confuse.Config;
import java.net.ServerSocket;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Duration;
import java.util.List;
import java.util.concurrent.TimeUnit;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.Timeout;
import org.junit.jupiter.api.io.TempDir;

/**
 * Each slice of a distributed step with {@code load-op-retry} on ends its own Steady-State Window
 * when its part of a finite input is exhausted. Both Engine Participants run in this JVM, over RMI on
 * the loopback interface, each with a latency driver whose last operation is slow.
 */
@Timeout(120)
class LinearLoadStepClientRetryFiniteSliceTest {

	private static final String RMI_HOSTNAME = "java.rmi.server.hostname";
	private static final int C = 8;
	private static final long L_MILLIS = 25;
	private static final int ITEMS_PER_SLICE = 12 * C;
	private static final long TAIL_MILLIS = 800;
	private static final long TERMINAL_RETENTION_MILLIS = TimeUnit.MINUTES.toMillis(10);

	@TempDir
	Path tempDir;

	@Test
	void eachSliceClosesItsWindowAtExhaustion() throws Exception {
		final StringBuilder lines = new StringBuilder();
		for (int i = 0; i < 2 * ITEMS_PER_SLICE; i++) {
			lines.append("/steady-bucket/item-").append(i).append(',').append(i).append(",1024,0/0\n");
		}
		final int port;
		try (ServerSocket socket = new ServerSocket(0)) {
			socket.setReuseAddress(true);
			port = socket.getLocalPort();
		}
		final Config config = createStepConfig("retry-finite-slice", C);
		config.val("load-step-idAutoGenerated", false);
		config.val("load-step-node-addrs", List.of("127.0.0.1:" + port));
		config.val("item-input-file", Files.writeString(tempDir.resolve("items.csv"), lines).toString());
		// An operation type that leaves no artifact: both participants share one file system.
		config.val("load-op-type", "noop");
		config.val("load-batch-size", 1024);
		config.val("load-op-retry", true);
		steadySettings(config, 1.0, 5.0, 0.2);

		final String originalRmiHostname = System.getProperty(RMI_HOSTNAME);
		System.setProperty(RMI_HOSTNAME, "127.0.0.1");
		final MetricsManagerImpl entryMetrics = metricsManager();
		final MetricsManagerImpl workerMetrics = metricsManager();
		final FileManagerServiceImpl files = new FileManagerServiceImpl(port);
		LoadStepManagerServiceImpl steps = null;
		LinearLoadStepClient client = null;
		try {
			files.start();
			steps = new LoadStepManagerServiceImpl(port, extensions(), workerMetrics);
			steps.start();
			client = new LinearLoadStepClient(config, extensions(), List.of(), entryMetrics);
			assertTimeoutPreemptively(Duration.ofSeconds(60), client::run);

			assertClosedAtExhaustion(entryMetrics);
			assertClosedAtExhaustion(workerMetrics);
		} finally {
			if (client != null && !client.isClosed()) {
				client.close();
			}
			if (steps != null && !steps.isClosed()) {
				steps.close();
			}
			if (!files.isClosed()) {
				files.close();
			}
			ServiceUtil.shutdown();
			if (originalRmiHostname == null) {
				System.clearProperty(RMI_HOSTNAME);
			} else {
				System.setProperty(RMI_HOSTNAME, originalRmiHostname);
			}
		}
	}

	private static void assertClosedAtExhaustion(final MetricsManagerImpl metrics) {
		final List<TerminalStepEntry> slices = metrics.getTerminalSteps().stream()
						.filter(entry -> !entry.distributed)
						.toList();
		assertEquals(1, slices.size(), metrics.getTerminalSteps().toString());
		final TerminalStepEntry slice = slices.get(0);
		assertEquals(ITEMS_PER_SLICE, slice.successCount);
		assertEquals("scheduling exhaustion", slice.steady.cause(), slice.steady.toString());
	}

	private static MetricsManagerImpl metricsManager() {
		final MetricsManagerImpl metrics = new MetricsManagerImpl(ServiceTaskExecutor.VT_EXECUTOR);
		metrics.setTerminalRetentionMillis(TERMINAL_RETENTION_MILLIS);
		return metrics;
	}

	private static List<Extension> extensions() {
		return List.of(
						new LinearLoadStepExtension<>(),
						new LatencyDriverExtension<>(() -> LatencyStorageDriver.data(C, L_MILLIS)
										.inputQueue(1_000_000)
										.slowTail(ITEMS_PER_SLICE - 1, TAIL_MILLIS, 0)));
	}
}
