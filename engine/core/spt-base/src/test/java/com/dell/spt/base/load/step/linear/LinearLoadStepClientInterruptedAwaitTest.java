/**
 * A distributed step whose waiting thread is interrupted mid-step, as {@code /shutdown} and
 * {@code DELETE /run} do, still writes its totals and keeps its terminal entry.
 *
 * <p>The client step, both slices, the metrics aggregation and the RMI transfer over the
 * loopback interface are the real ones. The second slice runs behind the services of a second
 * Engine Participant in this JVM, which has a metrics manager of its own.
 */
@Timeout(120)
class LinearLoadStepClientInterruptedAwaitTest {

	private static final long WAIT_MILLIS = 20_000;
	private static final String RMI_HOSTNAME = "java.rmi.server.hostname";

	private final Config config = TestConfigBuilder.config();
	private final MetricsManagerImpl entryMgr = new MetricsManagerImpl(ServiceTaskExecutor.VT_EXECUTOR);
	private final MetricsManagerImpl workerMgr = new MetricsManagerImpl(ServiceTaskExecutor.VT_EXECUTOR);
	private String stepId;
	private String originalRmiHostname;
	private FileManagerServiceImpl fileService;
	private LoadStepManagerServiceImpl stepManager;
	private LinearLoadStepClient client;
	private CapturingAppender totals;
	private Logger totalsLogger;

	@BeforeEach
	void startTheWorker() throws Exception {
		entryMgr.setTerminalRetentionMillis(30_000);
		workerMgr.setTerminalRetentionMillis(30_000);
		final int port;
		try (ServerSocket socket = new ServerSocket(0)) {
			socket.setReuseAddress(true);
			port = socket.getLocalPort();
		}
		originalRmiHostname = System.getProperty(RMI_HOSTNAME);
		System.setProperty(RMI_HOSTNAME, "127.0.0.1");
		fileService = new FileManagerServiceImpl(port);
		fileService.start();
		stepManager = new LoadStepManagerServiceImpl(port, extensions(), workerMgr);
		stepManager.start();

		stepId = "interrupted-await-" + System.nanoTime();
		totals = new CapturingAppender(stepId);
		totals.start();
		totalsLogger = LoggerContext.getContext(false).getLogger(Loggers.METRICS_FILE_TOTAL.getName());
		totalsLogger.addAppender(totals);

		config.val("load-step-id", stepId);
		config.val("load-step-idAutoGenerated", false);
		config.val("load-step-node-addrs", List.of("127.0.0.1:" + port));
		config.val("output-metrics-timing-persist", false);
		config.val("output-metrics-trace-persist", false);
		config.val("output-metrics-summary-persist", true);
		config.val("item-data-input-compressibility", 0.0);
		config.val("item-data-dedupable", false);
		config.val("item-data-verify", false);
		config.val("item-data-ranges-concat", null);
		// New items, and an operation type that leaves no artifact for the step to merge when it
		// closes: the two participants of this test share one file system.
		config.val("item-input-file", null);
		config.val("item-input-path", null);
		config.val("load-op-type", "noop");
		// Far longer than the test: only the interrupt ends the step.
		config.val("load-op-limit-count", 0);
		config.val("load-step-limit-time", "10m");
		config.val("load-op-wait-finish", true);
		config.val("load-op-wait-limit", 1);
	}

	@AfterEach
	void closeAll() throws Exception {
		try {
			if (totalsLogger != null) {
				totalsLogger.removeAppender(totals);
				totals.stop();
			}
			if (client != null && !client.isClosed()) {
				client.close();
			}
			if (stepManager != null && !stepManager.isClosed()) {
				stepManager.close();
			}
			if (fileService != null && !fileService.isClosed()) {
				fileService.close();
			}
		} finally {
			ServiceUtil.shutdown();
			if (originalRmiHostname == null) {
				System.clearProperty(RMI_HOSTNAME);
			} else {
				System.setProperty(RMI_HOSTNAME, originalRmiHostname);
			}
		}
	}

	@Test
	void interruptedAwaitOfTwoSlicesStillWritesTheTotals() throws Exception {
		client = new LinearLoadStepClient(config, extensions(), List.of(), entryMgr);
		client.start();
		assertTrue(client.isStarted(), "the step must start: " + client.state());
		final DistributedMetricsContext<?> fleet = onlyFleetContext();
		await(() -> {
			fleet.refreshLastSnapshot();
			final var snapshot = fleet.lastSnapshot();
			return snapshot != null && snapshot.successSnapshot().count() > 0 && snapshot.nodeCount() == 2;
		}, () -> "fleet progress " + fleet.lastSnapshot());

		final AtomicBoolean interruptedAfter = new AtomicBoolean();
		final AtomicReference<Throwable> awaitOutcome = new AtomicReference<>();
		final CompletableFuture<Void> done = new CompletableFuture<>();
		final Thread thread = Thread.ofPlatform().name("interrupted-await-waiter").start(() -> {
			try {
				client.await(10, TimeUnit.MINUTES);
			} catch (final Throwable e) {
				awaitOutcome.set(e);
			} finally {
				interruptedAfter.set(Thread.currentThread().isInterrupted());
				done.complete(null);
			}
		});
		// Let the waiter reach the slices' polling loop before the interrupt lands.
		Thread.sleep(500);
		assertFalse(done.isDone(), "the step must still be running: " + awaitOutcome.get());
		thread.interrupt();
		done.get(WAIT_MILLIS, TimeUnit.MILLISECONDS);

		assertTrue(awaitOutcome.get() instanceof InterruptedException, "await outcome: " + awaitOutcome.get());
		final List<TerminalStepEntry> fleetEntries = entryMgr.getTerminalSteps().stream()
						.filter(entry -> entry.distributed && stepId.equals(entry.stepId))
						.toList();
		assertEquals(1, fleetEntries.size(), () -> describe(entryMgr.getTerminalSteps()));
		assertTrue(fleetEntries.get(0).successCount > 0, () -> describe(fleetEntries));
		assertEquals(2, fleetEntries.get(0).nodeCount);
		await(() -> {
			LogUtil.flushAll();
			return totalRows().size() >= 2;
		}, () -> "metrics.total.csv rows " + totals.messages());
		final List<String> rows = totalRows();
		assertTrue(rows.get(0).startsWith("DateTimeISO8601,"), rows.toString());
		assertEquals(2, rows.size(), "header and one totals row: " + rows);
		assertTrue(entryMgr.getDistributedContexts().isEmpty(), "the fleet context must be unregistered");
		// The waiting thread polls the remote slice, so the interrupt flag is still set when the step
		// stops; writing the totals must leave it set for the caller.
		assertTrue(interruptedAfter.get(), "the waiter's interrupt flag must survive the step's stop");
	}

	@Test
	void interruptedRunClosesTheStepAndItsWorkerSlice() throws Exception {
		client = new LinearLoadStepClient(config, extensions(), List.of(), entryMgr);
		final AtomicBoolean interruptedAfter = new AtomicBoolean();
		final AtomicReference<Throwable> runOutcome = new AtomicReference<>();
		final CompletableFuture<Void> done = new CompletableFuture<>();
		final Thread thread = Thread.ofPlatform().name("interrupted-run").start(() -> {
			try {
				client.run();
			} catch (final Throwable e) {
				runOutcome.set(e);
			} finally {
				interruptedAfter.set(Thread.currentThread().isInterrupted());
				done.complete(null);
			}
		});
		await(() -> entryMgr.getDistributedContexts().size() == 1, () -> "fleet context of " + stepId);
		final DistributedMetricsContext<?> fleet = onlyFleetContext();
		await(() -> {
			fleet.refreshLastSnapshot();
			final var snapshot = fleet.lastSnapshot();
			return snapshot != null && snapshot.successSnapshot().count() > 0 && snapshot.nodeCount() == 2;
		}, () -> "fleet progress " + fleet.lastSnapshot());
		// Let the run thread reach the slices' polling loop before the interrupt lands.
		Thread.sleep(500);
		assertFalse(done.isDone(), "the step must still be running: " + runOutcome.get());
		thread.interrupt();
		done.get(WAIT_MILLIS, TimeUnit.MILLISECONDS);

		assertTrue(runOutcome.get() instanceof InterruptedException, "run outcome: " + runOutcome.get());
		assertTrue(client.isClosed(), "the step must close in its run, not at JVM exit: " + client.state());
		assertTrue(
						stepManager.getStepService().isClosed(),
						"the worker's step slice must close in the run, not at JVM exit");
		// The InterruptedException carries the stop out of run(), with the flag clear as on 3227d078.
		assertFalse(interruptedAfter.get(), "run() must throw with the interrupt flag clear");
		await(() -> {
			LogUtil.flushAll();
			return totalRows().size() >= 2;
		}, () -> "metrics.total.csv rows " + totals.messages());
	}

	private static String describe(final List<TerminalStepEntry> entries) {
		return entries.stream()
						.map(entry -> entry.stepId + (entry.distributed ? " (fleet)" : " (node)") + " successes=" + entry.successCount)
						.toList()
						.toString();
	}

	private List<String> totalRows() {
		return totals.messages().stream().flatMap(String::lines).filter(line -> !line.isBlank()).toList();
	}

	private static List<Extension> extensions() {
		return List.of(new LinearLoadStepExtension<>(), new DummyStorageDriverMockExtension<>());
	}

	private DistributedMetricsContext<?> onlyFleetContext() {
		@SuppressWarnings("rawtypes")
		final Set<DistributedMetricsContext> fleets = entryMgr.getDistributedContexts();
		assertEquals(1, fleets.size(), fleets.toString());
		return fleets.iterator().next();
	}

	private static void await(final BooleanSupplier condition, final Supplier<String> reached)
					throws InterruptedException {
		final long deadline = System.nanoTime() + TimeUnit.MILLISECONDS.toNanos(WAIT_MILLIS);
		while (!condition.getAsBoolean()) {
			assertTrue(System.nanoTime() < deadline, () -> "not reached in " + WAIT_MILLIS + " ms: " + reached.get());
			Thread.sleep(10);
		}
	}

	private static final class CapturingAppender extends AbstractAppender {
		private final String stepId;
		private final List<String> captured = Collections.synchronizedList(new ArrayList<>());

		CapturingAppender(final String stepId) {
			super("interruptedAwaitTotalsCapture", null, null, true, Property.EMPTY_ARRAY);
			this.stepId = stepId;
		}

		@Override
		public void append(final LogEvent event) {
			if (stepId.equals(event.getContextData().getValue(KEY_STEP_ID))) {
				captured.add(event.getMessage().getFormattedMessage());
			}
		}

		List<String> messages() {
			synchronized (captured) {
				return List.copyOf(captured);
			}
		}
	}
}
