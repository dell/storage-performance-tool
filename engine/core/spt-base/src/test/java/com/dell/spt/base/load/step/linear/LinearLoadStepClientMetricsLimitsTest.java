package com.dell.spt.base.load.step.linear;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.mockito.Mockito.mock;

import com.dell.spt.base.config.TestConfigBuilder;
import com.dell.spt.base.load.step.LoadStepBase;
import com.dell.spt.base.metrics.MetricsConstants;
import com.dell.spt.base.metrics.MetricsManager;
import com.dell.spt.base.metrics.context.DistributedMetricsContext;
import com.dell.spt.base.metrics.context.MetricsContext;
import com.github.akurilov.confuse.Config;
import java.lang.reflect.Field;
import java.util.List;
import java.util.Map;
import org.junit.jupiter.api.Test;

/** A linear step runs on its base and ignores its contexts, so its metrics row takes the base's limits. */
class LinearLoadStepClientMetricsLimitsTest {

	@Test
	void theRowOfAnAppendedStepTakesTheBasesLimitsAndBucketSettings() throws Exception {
		final Config config = TestConfigBuilder.config();
		config.val("load-step-id", "linear-limits-" + System.nanoTime());
		config.val("load-step-idAutoGenerated", false);
		config.val("load-step-limit-time", "12s");
		config.val("load-op-limit-count", 0L);
		config.val("load-op-type", "read");
		final LinearLoadStepClient client = new LinearLoadStepClient(config, List.of(), null, mock(MetricsManager.class))
						.append(Map.of(
										"load", Map.of(
														"op", Map.of("limit", Map.of("count", 50L)),
														"step", Map.of("limit", Map.of("time", "3s"))),
										"storage", Map.of("targetBucket", Map.of("count", 2))));

		client.init();

		final List<MetricsContext<?>> rows = metricsContextsOf(client);
		assertEquals(1, rows.size());
		final MetricsContext<?> row = rows.get(0);
		assertEquals(0L, limit(row, MetricsConstants.METADATA_LIMIT_OP_COUNT));
		assertEquals(12L, limit(row, MetricsConstants.METADATA_LIMIT_TIME_SEC));
		assertNull(((DistributedMetricsContext) row).bucketMetricsSource(), "the slice records no buckets");
	}

	private static long limit(final MetricsContext<?> row, final String key) {
		final Object value = row.metadata().get(key);
		assertNotNull(value, key);
		return ((Number) value).longValue();
	}

	@SuppressWarnings("unchecked")
	private static List<MetricsContext<?>> metricsContextsOf(final LoadStepBase step) throws ReflectiveOperationException {
		final Field field = LoadStepBase.class.getDeclaredField("metricsContexts");
		field.setAccessible(true);
		return (List<MetricsContext<?>>) field.get(step);
	}
}
