/**
 * A stop that lands after a step's await has ended, while the step writes its totals, still ends
 * the scenario at that step: the step closes and writes its totals, its {@code run()} throws
 * {@link InterruptedException}, and the scenario's next statement and step do not run.
 *
 * <p>The stop is the interrupt that {@code /shutdown} and {@code DELETE /run} deliver to the
 * scenario thread. It is set at entry to the production {@link MetricsManagerImpl#unregister} of
 * the step's context on the run thread, which is where the await has ended and the step's stop is
 * under way.
 */
@Timeout(120)
class LinearLoadStepClientStopAtCloseTest {

	private static final long WAIT_MILLIS = 20_000;
	private static final String RMI_HOSTNAME = "java.rmi.server.hostname";

	private final Config config = TestConfigBuilder.config();
	private final List<AutoCloseable> closeables = new ArrayList<>();
	private String firstStepId;
	private String originalRmiHostname;
	private CapturingAppender totals;
	private Logger totalsLogger;

	@BeforeEach
	void configure() {
		originalRmiHostname = System.getProperty(RMI_HOSTNAME);
		System.setProperty(RMI_HOSTNAME, "127.0.0.1");
		firstStepId = "stop-at-close-" + System.nanoTime();
		totals = new CapturingAppender(firstStepId);
		totals.start();
		totalsLogger = LoggerContext.getContext(false).getLogger(Loggers.METRICS_FILE_TOTAL.getName());
		totalsLogger.addAppender(totals);

		config.val("load-step-idAutoGenerated", false);
		config.val("output-metrics-timing-persist", false);
		config.val("output-metrics-trace-persist", false);
		config.val("output-metrics-summary-persist", true);
		config.val("item-data-input-compressibility", 0.0);
		config.val("item-data-dedupable", false);
		config.val("item-data-verify", false);
		config.val("item-data-ranges-concat", null);
		config.val("item-input-file", null);
		config.val("item-input-path", null);
		config.val("load-op-type", "noop");
		// The count limit ends the step's await; the stop comes after it.
		config.val("load-op-limit-count", 200);
		config.val("load-step-limit-time", "10m");
		config.val("load-op-wait-finish", true);
		config.val("load-op-wait-limit", 1);
	}

	@AfterEach
	void closeAll() throws Exception {
		try {
			totalsLogger.removeAppender(totals);
			totals.stop();
			for (final AutoCloseable closeable : closeables.reversed()) {
				closeable.close();
			}
		} finally {
			ServiceUtil.shutdown();
			if (originalRmiHostname == null) {
				System.clearProperty(RMI_HOSTNAME);
			} else {
				System.setProperty(RMI_HOSTNAME, originalRmiHostname);
			}
		}
	}

	@Test
	void singleEngineStopAtCloseEndsTheScenarioAtThatStep() throws Exception {
		config.val("load-step-node-addrs", List.of());
		final StopAtUnregister entryMgr = new StopAtUnregister(firstStepId, false);
		runTwoSteps(entryMgr);
	}

	@Test
	void distributedStopAtCloseEndsTheScenarioAtThatStep() throws Exception {
		final int port;
		try (ServerSocket socket = new ServerSocket(0)) {
			socket.setReuseAddress(true);
			port = socket.getLocalPort();
		}
		final FileManagerServiceImpl fileService = new FileManagerServiceImpl(port);
		fileService.start();
		closeables.add(() -> {
			if (!fileService.isClosed()) {
				fileService.close();
			}
		});
		final MetricsManagerImpl workerMgr = new MetricsManagerImpl(ServiceTaskExecutor.VT_EXECUTOR);
		final LoadStepManagerServiceImpl stepManager = new LoadStepManagerServiceImpl(port, extensions(), workerMgr);
		stepManager.start();
		closeables.add(() -> {
			if (!stepManager.isClosed()) {
				stepManager.close();
			}
		});
		config.val("load-step-node-addrs", List.of("127.0.0.1:" + port));
		final StopAtUnregister entryMgr = new StopAtUnregister(firstStepId, true);
		runTwoSteps(entryMgr);
	}

	/** Runs the scenario {@code first.run(); next = true; second.run();} on one thread. */
	private void runTwoSteps(final StopAtUnregister entryMgr) throws Exception {
		entryMgr.setTerminalRetentionMillis(30_000);
		final AtomicBoolean nextStatementRan = new AtomicBoolean();
		final AtomicInteger stepsStarted = new AtomicInteger();
		final AtomicReference<Throwable> outcome = new AtomicReference<>();
		final AtomicBoolean interruptedAfter = new AtomicBoolean();
		final CompletableFuture<Void> done = new CompletableFuture<>();
		Thread.ofPlatform().name("scenario").start(() -> {
			try {
				final LinearLoadStepClient first = step(firstStepId, entryMgr);
				stepsStarted.incrementAndGet();
				first.run();
				nextStatementRan.set(true);
				final LinearLoadStepClient second = step(firstStepId + "-next", entryMgr);
				stepsStarted.incrementAndGet();
				second.run();
			} catch (final Throwable e) {
				outcome.set(e);
			} finally {
				interruptedAfter.set(Thread.currentThread().isInterrupted());
				done.complete(null);
			}
		});
		done.get(WAIT_MILLIS * 3, TimeUnit.MILLISECONDS);

		assertTrue(entryMgr.stopped.get(), "the stop must land at the step's unregister on the run thread");
		assertTrue(outcome.get() instanceof InterruptedException, "first run() outcome: " + outcome.get());
		assertFalse(nextStatementRan.get(), "the statement after the stopped step must not run");
		assertEquals(1, stepsStarted.get(), "the step after the stopped one must not run");
		assertFalse(interruptedAfter.get(), "run() throws with the flag clear, as the await's interrupt does");
		await(() -> {
			LogUtil.flushAll();
			return totalRows().size() >= 2;
		}, () -> "metrics.total.csv rows " + totals.messages());
		final List<String> rows = totalRows();
		assertTrue(rows.get(0).startsWith("DateTimeISO8601,"), rows.toString());
		assertEquals(2, rows.size(), "header and one totals row: " + rows);
	}

	private LinearLoadStepClient step(final String stepId, final MetricsManagerImpl entryMgr) {
		config.val("load-step-id", stepId);
		final LinearLoadStepClient step = new LinearLoadStepClient(config, extensions(), List.of(), entryMgr);
		closeables.add(() -> {
			if (!step.isClosed()) {
				step.close();
			}
		});
		return step;
	}

	private List<String> totalRows() {
		return totals.messages().stream().flatMap(String::lines).filter(line -> !line.isBlank()).toList();
	}

	private static List<Extension> extensions() {
		return List.of(new LinearLoadStepExtension<>(), new DummyStorageDriverMockExtension<>());
	}

	private static void await(final BooleanSupplier condition, final Supplier<String> reached)
					throws InterruptedException {
		final long deadline = System.nanoTime() + TimeUnit.MILLISECONDS.toNanos(WAIT_MILLIS);
		while (!condition.getAsBoolean()) {
			assertTrue(System.nanoTime() < deadline, () -> "not reached in " + WAIT_MILLIS + " ms: " + reached.get());
			Thread.sleep(10);
		}
	}

	/**
	 * The production metrics manager, which interrupts the scenario thread once, at entry to the
	 * unregister of the first step's context: the fleet context of a distributed step, or the
	 * node context of a single-engine step.
	 */
	private static final class StopAtUnregister extends MetricsManagerImpl {
		private final String stepId;
		private final boolean distributed;
		final AtomicBoolean stopped = new AtomicBoolean();

		StopAtUnregister(final String stepId, final boolean distributed) {
			super(ServiceTaskExecutor.VT_EXECUTOR);
			this.stepId = stepId;
			this.distributed = distributed;
		}

		@Override
		public void unregister(final MetricsContext metricsCtx) {
			if (stepId.equals(metricsCtx.loadStepId())
							&& distributed == metricsCtx instanceof DistributedMetricsContext
							&& "scenario".equals(Thread.currentThread().getName())
							&& stopped.compareAndSet(false, true)) {
				Thread.currentThread().interrupt();
			}
			super.unregister(metricsCtx);
		}
	}

	private static final class CapturingAppender extends AbstractAppender {
		private final String stepId;
		private final List<String> captured = Collections.synchronizedList(new ArrayList<>());

		CapturingAppender(final String stepId) {
			super("stopAtCloseTotalsCapture", null, null, true, Property.EMPTY_ARRAY);
			this.stepId = stepId;
		}

		@Override
		public void append(final LogEvent event) {
			if (stepId.equals(event.getContextData().getValue(KEY_STEP_ID))) {
				captured.add(event.getMessage().getFormattedMessage());
			}
		}

		List<String> messages() {
			synchronized (captured) {
				return List.copyOf(captured);
			}
		}
	}
}
