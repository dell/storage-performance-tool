package com.dell.spt.base.load.step.linear;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTimeoutPreemptively;

import com.dell.spt.base.concurrent.ServiceTaskExecutor;
import com.dell.spt.base.config.TestConfigBuilder;
import com.dell.spt.base.control.run.RunTerminalException;
import com.dell.spt.base.env.Extension;
import com.dell.spt.base.integrity.IntegrityTerminalException;
import com.dell.spt.base.load.step.service.LoadStepManagerServiceImpl;
import com.dell.spt.base.load.step.service.file.FileManagerServiceImpl;
import com.dell.spt.base.metrics.MetricsManagerImpl;
import com.dell.spt.base.metrics.TerminalStepEntry;
import com.dell.spt.base.storage.driver.mock.DummyStorageDriverMockExtension;
import com.dell.spt.base.svc.ServiceUtil;
import com.github.akurilov.confuse.Config;
import com.github.akurilov.confuse.impl.BasicConfig;
import java.net.ServerSocket;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Duration;
import java.util.ArrayList;
import java.util.List;
import java.util.concurrent.TimeUnit;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.Timeout;
import org.junit.jupiter.api.io.TempDir;

/**
 * How a distributed count-limited step gives each of its Engine Participants a count. A slice
 * reads a count of 0 as no limit, so a count that can't give each engine at least 1 fails the run
 * before it starts, and so does a count-based recycle step with an engine that would get no items.
 *
 * <p>The client step, the slices, the item scatter and the transfer between Engine Participants
 * (RMI over the loopback interface) are the real ones; the storage driver is the dummy mock. Each
 * remote slice runs behind the services of another Engine Participant in this JVM.
 */
@Timeout(180)
class LinearLoadStepClientCountSlicesTest {

	private static final String RMI_HOSTNAME = "java.rmi.server.hostname";
	// Bounds each engine to 50 operations per second, should a slice ever run without a count.
	private static final double RATE_LIMIT = 100;
	private static final Duration RUN_TIMEOUT = Duration.ofSeconds(60);
	// Longer than any run here may take, so a step's final entries are still kept when it is read.
	private static final long TERMINAL_RETENTION_MILLIS = TimeUnit.MINUTES.toMillis(10);

	private final Config config = TestConfigBuilder.config();
	private final MetricsManagerImpl entryMgr = new MetricsManagerImpl(ServiceTaskExecutor.VT_EXECUTOR);
	private final List<Worker> workers = new ArrayList<>();
	private String originalRmiHostname;
	private LinearLoadStepClient client;

	@TempDir
	Path tempDir;

	/** The services of one more Engine Participant, at a port of its own. */
	private record Worker(
					String addr, MetricsManagerImpl metrics, FileManagerServiceImpl files, LoadStepManagerServiceImpl steps) {}

	@BeforeEach
	void configureTheStep() {
		entryMgr.setTerminalRetentionMillis(TERMINAL_RETENTION_MILLIS);
		originalRmiHostname = System.getProperty(RMI_HOSTNAME);
		System.setProperty(RMI_HOSTNAME, "127.0.0.1");

		config.val("load-step-id", "count-slices-" + System.nanoTime());
		config.val("load-step-idAutoGenerated", false);
		config.val("load-step-limit-time", 0);
		config.val("storage-driver-type", "dummy-mock");
		config.val("output-metrics-timing-persist", false);
		config.val("output-metrics-trace-persist", false);
		config.val("item-data-input-compressibility", 0.0);
		config.val("item-data-dedupable", false);
		config.val("item-data-verify", false);
		config.val("item-data-ranges-concat", null);
		// New items, and an operation type that leaves no artifact for the step to merge when it closes:
		// the participants of this test share one file system.
		config.val("item-input-file", null);
		config.val("item-input-path", null);
		config.val("load-op-type", "noop");
		config.val("load-op-limit-rate", RATE_LIMIT);
		config.val("load-op-wait-finish", true);
		config.val("load-op-wait-limit", 1);
	}

	/** Starts this many more Engine Participants and gives the step all of them. */
	private void startWorkers(final int count) throws Exception {
		final List<String> addrs = new ArrayList<>(count);
		for (int i = 0; i < count; i++) {
			final int port;
			try (ServerSocket socket = new ServerSocket(0)) {
				socket.setReuseAddress(true);
				port = socket.getLocalPort();
			}
			final MetricsManagerImpl metrics = new MetricsManagerImpl(ServiceTaskExecutor.VT_EXECUTOR);
			metrics.setTerminalRetentionMillis(TERMINAL_RETENTION_MILLIS);
			final FileManagerServiceImpl files = new FileManagerServiceImpl(port);
			files.start();
			final LoadStepManagerServiceImpl steps = new LoadStepManagerServiceImpl(port, extensions(), metrics);
			steps.start();
			final Worker worker = new Worker("127.0.0.1:" + port, metrics, files, steps);
			workers.add(worker);
			addrs.add(worker.addr());
		}
		config.val("load-step-node-addrs", addrs);
	}

	@AfterEach
	void closeAll() throws Exception {
		try {
			if (client != null && !client.isClosed()) {
				client.close();
			}
			for (final Worker worker : workers) {
				if (!worker.steps().isClosed()) {
					worker.steps().close();
				}
				if (!worker.files().isClosed()) {
					worker.files().close();
				}
			}
		} finally {
			ServiceUtil.shutdown();
			if (originalRmiHostname == null) {
				System.clearProperty(RMI_HOSTNAME);
			} else {
				System.setProperty(RMI_HOSTNAME, originalRmiHostname);
			}
		}
	}

	@Test
	void eachEngineDoesItsShareOfTheCountAndTheStepEnds() throws Exception {
		startWorkers(1);
		config.val("load-op-limit-count", 3L);
		client = new LinearLoadStepClient(config, extensions(), List.of(), entryMgr);
		assertTimeoutPreemptively(RUN_TIMEOUT, client::run);

		final TerminalStepEntry entryNode = entry(entryMgr, false);
		final TerminalStepEntry workerNode = entry(workers.get(0).metrics(), false);
		assertEquals(2, entryNode.countLimit);
		assertEquals(2, entryNode.successCount);
		assertEquals(1, workerNode.countLimit);
		assertEquals(1, workerNode.successCount);
		assertEquals(3, entry(entryMgr, true).successCount);
	}

	/** The ceil split of 4 on three engines is 2, 2 and 0, which left the third engine without a limit. */
	@Test
	void aCountWhoseCeilSplitLeavesAnEngineAtZeroIsSplitEvenly() throws Exception {
		startWorkers(2);
		config.val("load-op-limit-count", 4L);
		client = new LinearLoadStepClient(config, extensions(), List.of(), entryMgr);
		assertTimeoutPreemptively(RUN_TIMEOUT, client::run);

		final TerminalStepEntry entryNode = entry(entryMgr, false);
		assertEquals(2, entryNode.countLimit);
		assertEquals(2, entryNode.successCount);
		for (final Worker worker : workers) {
			final TerminalStepEntry workerNode = entry(worker.metrics(), false);
			assertEquals(1, workerNode.countLimit, worker.addr());
			assertEquals(1, workerNode.successCount, worker.addr());
		}
		assertEquals(4, entry(entryMgr, true).successCount);
	}

	@Test
	void aCountBelowTheEngineCountFailsBeforeTheStepStarts() throws Exception {
		startWorkers(1);
		config.val("load-op-limit-count", 1L);
		client = new LinearLoadStepClient(config, extensions(), List.of(), entryMgr);
		final RunTerminalException failure = assertTimeoutPreemptively(
						RUN_TIMEOUT, () -> assertThrows(RunTerminalException.class, client::run));
		assertEquals(IntegrityTerminalException.Category.CONFIGURATION, failure.category());
		assertEquals(
						"the count limit (1) is below the number of engines (2), and each engine needs a count of at least 1: "
										+ "raise the count limit to at least 2 (--object-count, or --seed-objects for a seed step), "
										+ "or pass fewer --test-hosts",
						failure.getMessage());
		assertEquals(List.of(), workers.get(0).metrics().getTerminalSteps(), "the worker's slice never started");
	}

	/**
	 * A linear step runs on its base configuration and ignores its contexts, so a context's count and
	 * items, which a slice never uses, fail nothing.
	 */
	@Test
	void aContextTheStepNeverUsesIsNotChecked() throws Exception {
		startWorkers(1);
		final Path items = tempDir.resolve("one.csv");
		Files.writeString(items, "/bucket/a,0,10,0/0\n");
		config.val("load-op-limit-count", 2L);
		final Config unused = new BasicConfig(config);
		unused.val("load-op-limit-count", 1L);
		unused.val("load-op-recycle-mode", true);
		unused.val("item-input-file", items.toString());
		client = new LinearLoadStepClient(config, extensions(), List.of(unused), entryMgr);
		assertTimeoutPreemptively(RUN_TIMEOUT, client::run);

		assertEquals(1, entry(entryMgr, false).successCount);
		assertEquals(1, entry(workers.get(0).metrics(), false).successCount);
		assertEquals(2, entry(entryMgr, true).successCount);
	}

	@Test
	void aCountBasedRecycleReadWithAnEngineWithoutItemsFailsBeforeTheStepStarts() throws Exception {
		startWorkers(1);
		final Path items = tempDir.resolve("one.csv");
		Files.writeString(items, "/bucket/a,0,10,0/0\n");
		config.val("item-input-file", items.toString());
		config.val("load-op-type", "read");
		config.val("load-op-recycle-mode", true);
		config.val("load-op-limit-count", 2L);
		client = new LinearLoadStepClient(config, extensions(), List.of(), entryMgr);
		final RunTerminalException failure = assertTimeoutPreemptively(
						RUN_TIMEOUT, () -> assertThrows(RunTerminalException.class, client::run));
		assertEquals(IntegrityTerminalException.Category.INPUT, failure.category());
		assertEquals(
						"the items file has 1 item for 2 engines; each engine needs at least one in a count-based read: "
										+ "add items, or pass fewer --test-hosts",
						failure.getMessage());
		assertEquals(List.of(), workers.get(0).metrics().getTerminalSteps(), "the worker's slice never started");
	}

	private static List<Extension> extensions() {
		return List.of(new LinearLoadStepExtension<>(), new DummyStorageDriverMockExtension<>());
	}

	/** The one entry a metrics manager kept for the step: its fleet's or its node's. */
	private static TerminalStepEntry entry(final MetricsManagerImpl mgr, final boolean distributed) {
		final List<TerminalStepEntry> entries = mgr.getTerminalSteps().stream()
						.filter(entry -> entry.distributed == distributed)
						.toList();
		assertEquals(1, entries.size(), mgr.getTerminalSteps().toString());
		assertNotNull(entries.get(0));
		return entries.get(0);
	}
}
