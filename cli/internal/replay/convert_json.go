func effectiveVariables(exports map[string]string, opts Options) map[string]string {
	vars := make(map[string]string, len(exports)+16)
	for k, v := range exports {
		vars[k] = v
	}
	hosts := endpointHosts(opts.Endpoints)
	if len(hosts) > 0 {
		rebindIndexedVars(vars, "DATA_NODE", hosts)
		vars["DATA_NODES"] = strings.Join(hosts, ",")
		vars["ALL_NODES"] = strings.Join(hosts, ",")
	}
	clients := testHostnames(opts.TestHosts)
	if len(clients) > 0 {
		rebindIndexedVars(vars, "CLIENT", clients)
		vars["CLIENTS"] = strings.Join(clients, ",")
	}
	return vars
}

func testHostnames(testHosts string) []string {
	hostInfos, err := hostparse.ParseTestHosts(testHosts)
	if err == nil && len(hostInfos) > 0 {
		hosts := make([]string, 0, len(hostInfos))
		for _, info := range hostInfos {
			if info != nil && strings.TrimSpace(info.Host) != "" {
				hosts = append(hosts, info.Host)
			}
		}
		if len(hosts) > 0 {
			return hosts
		}
	}

	rawHosts := splitCSV(testHosts)
	hosts := make([]string, 0, len(rawHosts))
	for _, raw := range rawHosts {
		host := raw
		if _, after, ok := strings.Cut(raw, "@"); ok {
			host = after
		}
		if strings.TrimSpace(host) != "" {
			hosts = append(hosts, strings.TrimSpace(host))
		}
	}
	return hosts
}

func rebindIndexedVars(vars map[string]string, base string, localValues []string) {
	maxIndex := len(localValues)
	for k := range vars {
		if k == base {
			continue
		}
		prefix := base + "_"
		if !strings.HasPrefix(k, prefix) {
			continue
		}
		idx, err := strconv.Atoi(strings.TrimPrefix(k, prefix))
		if err != nil {
			continue
		}
		if idx > maxIndex {
			maxIndex = idx
		}
	}
	vars[base] = localValues[0]
	for i := 2; i <= maxIndex; i++ {
		vars[fmt.Sprintf("%s_%d", base, i)] = localValues[(i-1)%len(localValues)]
	}
}

func endpointHosts(endpoints []string) []string {
	out := make([]string, 0, len(endpoints))
	for _, endpoint := range endpoints {
		endpoint = strings.TrimSpace(endpoint)
		if endpoint == "" {
			continue
		}
		u, err := url.Parse(endpoint)
		if err == nil && u.Hostname() != "" {
			out = append(out, u.Hostname())
			continue
		}
		host := endpoint
		if strings.Contains(host, ":") {
			if h, _, ok := strings.Cut(host, ":"); ok {
				host = h
			}
		}
		out = append(out, host)
	}
	return out
}

func splitCSV(value string) []string {
	parts := strings.Split(value, ",")
	out := make([]string, 0, len(parts))
	for _, part := range parts {
		if s := strings.TrimSpace(part); s != "" {
			out = append(out, s)
		}
	}
	return out
}

func writePreludeVars(b *strings.Builder, vars map[string]string) {
	keys := make([]string, 0, len(vars))
	for k := range vars {
		if isSensitiveName(k) || k == legacyMongooseDirVar {
			continue
		}
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		b.WriteString("var ")
		b.WriteString(k)
		b.WriteString(" = ")
		b.WriteString(jsQuote(vars[k]))
		b.WriteString(";\n")
	}
}

func writeReplayProcessHelpers(b *strings.Builder) {
	b.WriteString("function runReplayProcess(command, args, cwd) {\n")
	b.WriteString("  var commandLine = new java.util.ArrayList();\n")
	b.WriteString("  commandLine.add(String(command));\n")
	b.WriteString("  for (var i = 0; i < args.length; i++) { commandLine.add(String(args[i])); }\n")
	b.WriteString("  var processBuilder = new java.lang.ProcessBuilder(commandLine);\n")
	b.WriteString("  if (cwd) { processBuilder.directory(new java.io.File(String(cwd))); }\n")
	b.WriteString("  processBuilder.redirectErrorStream(true);\n")
	b.WriteString("  var process = processBuilder.start();\n")
	b.WriteString("  var reader = new java.io.BufferedReader(new java.io.InputStreamReader(process.getInputStream()));\n")
	b.WriteString("  var line;\n")
	b.WriteString("  while ((line = reader.readLine()) !== null) { if (line.length() > 0) { print(line); } }\n")
	b.WriteString("  var exitCode = process.waitFor();\n")
	b.WriteString("  if (exitCode !== 0) { throw \"Replay command failed (\" + exitCode + \"): \" + command + \" \" + args.join(\" \"); }\n")
	b.WriteString("}\n\n")
	b.WriteString("function runReplayProcessToFile(command, args, cwd, outputPath, append) {\n")
	b.WriteString("  var commandLine = new java.util.ArrayList();\n")
	b.WriteString("  commandLine.add(String(command));\n")
	b.WriteString("  for (var i = 0; i < args.length; i++) { commandLine.add(String(args[i])); }\n")
	b.WriteString("  var processBuilder = new java.lang.ProcessBuilder(commandLine);\n")
	b.WriteString("  if (cwd) { processBuilder.directory(new java.io.File(String(cwd))); }\n")
	b.WriteString("  var outputFile = new java.io.File(String(outputPath));\n")
	b.WriteString("  var parentDir = outputFile.getParentFile();\n")
	b.WriteString("  if (parentDir) { parentDir.mkdirs(); }\n")
	b.WriteString("  var redirect = append ? java.lang.ProcessBuilder.Redirect.appendTo(outputFile) : java.lang.ProcessBuilder.Redirect.to(outputFile);\n")
	b.WriteString("  processBuilder.redirectOutput(redirect);\n")
	b.WriteString("  processBuilder.redirectError(java.lang.ProcessBuilder.Redirect.INHERIT);\n")
	b.WriteString("  var exitCode = processBuilder.start().waitFor();\n")
	b.WriteString("  if (exitCode !== 0) { throw \"Replay command failed (\" + exitCode + \"): \" + command + \" \" + args.join(\" \"); }\n")
	b.WriteString("}\n\n")
}

func isSensitiveName(name string) bool {
	lower := strings.ToLower(name)
	if lower == "key" || lower == "user_id" {
		return true
	}
	return strings.Contains(lower, "secret") ||
		strings.Contains(lower, "password") ||
		strings.Contains(lower, "token") ||
		strings.Contains(lower, "auth") ||
		strings.Contains(lower, "access") ||
		strings.Contains(lower, "key")
}

