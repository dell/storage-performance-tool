func getPath(m map[string]any, path ...string) any {
	var cur any = m
	for _, p := range path {
		asMap, ok := cur.(map[string]any)
		if !ok {
			return nil
		}
		cur = asMap[p]
	}
	return cur
}

func firstPath(m map[string]any, paths ...[]string) any {
	for _, p := range paths {
		if v := getPath(m, p...); v != nil {
			return v
		}
	}
	return nil
}

func setPath(m map[string]any, value any, path ...string) {
	cur := m
	for _, p := range path[:len(path)-1] {
		next, ok := cur[p].(map[string]any)
		if !ok {
			next = map[string]any{}
			cur[p] = next
		}
		cur = next
	}
	cur[path[len(path)-1]] = value
}

func resolveString(v any, vars map[string]string) string {
	switch t := v.(type) {
	case nil:
		return ""
	case string:
		return expandWithExports(t, vars)
	case json.Number:
		return t.String()
	case float64:
		return strconv.FormatFloat(t, 'f', -1, 64)
	case bool:
		return strconv.FormatBool(t)
	default:
		return fmt.Sprint(t)
	}
}

func intValue(v any, vars map[string]string) int {
	n := int64Value(v, vars)
	if n > int64(^uint(0)>>1) {
		return 0
	}
	return int(n)
}

func int64Value(v any, vars map[string]string) int64 {
	switch t := v.(type) {
	case json.Number:
		n, _ := t.Int64()
		return n
	case float64:
		return int64(t)
	case int:
		return int64(t)
	case int64:
		return t
	case string:
		n, _ := strconv.ParseInt(strings.TrimSpace(expandWithExports(t, vars)), 10, 64)
		return n
	default:
		return 0
	}
}

func boolValue(v any, vars map[string]string) (bool, bool) {
	switch t := v.(type) {
	case bool:
		return t, true
	case string:
		b, err := strconv.ParseBool(strings.TrimSpace(expandWithExports(t, vars)))
		return b, err == nil
	default:
		return false, false
	}
}

func floatValue(v any, vars map[string]string) (float64, bool) {
	switch t := v.(type) {
	case json.Number:
		n, err := t.Float64()
		return n, err == nil
	case float64:
		return t, true
	case float32:
		return float64(t), true
	case int:
		return float64(t), true
	case int64:
		return float64(t), true
	case string:
		n, err := strconv.ParseFloat(strings.TrimSpace(expandWithExports(t, vars)), 64)
		return n, err == nil
	default:
		return 0, false
	}
}

func stringListValue(v any, vars map[string]string) ([]string, bool) {
	switch t := v.(type) {
	case []any:
		values := make([]string, 0, len(t))
		for _, raw := range t {
			value := strings.TrimSpace(resolveString(raw, vars))
			if value == "" {
				continue
			}
			values = append(values, value)
		}
		return values, len(values) > 0
	case []string:
		values := make([]string, 0, len(t))
		for _, raw := range t {
			value := strings.TrimSpace(expandWithExports(raw, vars))
			if value == "" {
				continue
			}
			values = append(values, value)
		}
		return values, len(values) > 0
	case string:
		values := splitCSV(expandWithExports(t, vars))
		return values, len(values) > 0
	default:
		return nil, false
	}
}

func durationValue(v any, vars map[string]string) string {
	s := strings.TrimSpace(resolveString(v, vars))
	if s == "" {
		return ""
	}
	if _, err := strconv.Atoi(s); err == nil {
		return s + "s"
	}
	return s
}

func unresolvedVars(v any, vars map[string]string) []string {
	s, ok := v.(string)
	if !ok || s == "" {
		return nil
	}
	var missing []string
	matches := expandVarRe.FindAllStringSubmatch(s, -1)
	for _, match := range matches {
		if len(match) != 2 {
			continue
		}
		value, ok := vars[match[1]]
		if !ok || strings.TrimSpace(value) == "" {
			missing = append(missing, match[1])
		}
	}
	return missing
}

